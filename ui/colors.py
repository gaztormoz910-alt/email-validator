"""Палитра тёмной темы. Каждая пара проверена расчётом, а не глазом.

Почему это отдельный файл с объяснениями, а не двадцать констант. Тёмная тема
легко выглядит аккуратной и при этом не читается: серый на почти чёрном
кажется стильным дизайнеру со свежими глазами на хорошем мониторе — и
пропадает у того, кто сидит перед окном восемь часов подряд. Проверяется это
не мнением, а формулой контраста WCAG, и на неё есть инструмент:

    python tools/check_contrast.py

До переделки три пары порог не проходили: подсказки давали 2.79:1 и 2.67:1
при норме 4.5:1, а белый текст на кнопке действия — 4.47:1. Подсказки — это
как раз те строки, которые объясняют новичку, что делает переключатель, и
именно они были нечитаемы.

УСТРОЙСТВО ПАЛИТРЫ

Тон — холодный сине-серый вместо прежнего нейтрально-чёрного. Причина не
вкусовая: у чисто серых поверхностей нет направления, и слои различаются
только светлотой, а на дешёвой матрице ступени между #131316 и #18181B
сливаются в одно пятно. Синий подмес даёт слоям различимость даже там, где
разница в яркости теряется.

Акцентов ровно два, и у них разные работы:
  ACCENT_PRIMARY — ДЕЙСТВИЕ и фокус. Голубой, светлый, с тёмным текстом
                   поверх. Светлая заливка с тёмным текстом на тёмной теме
                   читается лучше тёмной с белым: у неё выше контраст и с
                   фоном, и с собственным текстом.
  ACCENT_SUCCESS — РЕЗУЛЬТАТ «годен». Зелёный отделён от акцента действия
                   намеренно: иначе «нажми сюда» и «это хорошо» становятся
                   одним сигналом, и пользователь перестаёт различать
                   кнопку и статус.

Статусные цвета десатурированы: полностью насыщенный красный на тёмном фоне
звенит и утомляет, а нужен он на каждой второй строке таблицы.
"""

