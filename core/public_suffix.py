# -*- coding: utf-8 -*-
"""Список публичных суффиксов Mozilla: где кончается чужая зона и начинается
чей-то домен.

ЗАЧЕМ ОН ЗДЕСЬ. Два места программы держались на самодельном списке зон из
ста семи имён, и оба из-за этого врали.

**Очистка домена.** `core/cleaner.py` отрезает мусор, приклеенный к зоне:
`yandex.rublahblah` -> `yandex.ru`. Чтобы понять, где зона кончается, ей нужен
список зон. Пока он был короткий, настоящая зона, которой в нём не оказалось,
принималась за «короткая зона плюс мусор», и домен уезжал на ЧУЖОЙ. Замерено
на этом файле: из 1181 настоящей зоны, которых в самодельном списке не было,
очистка калечила 41:

    mycompany.deloitte  ->  mycompany.de
    mycompany.chanel    ->  mycompany.ch
    mycompany.dentist   ->  mycompany.de
    mycompany.archi     ->  mycompany.ar

Каждая такая строка — вердикт о постороннем человеке.

**Фильтр одноразовых.** `core/disposable.py` хоронит поддомены известных
сервисов: `foo.mailinator.com` ловится по родителю `mailinator.com`. Но база
пополняется скачанными списками, а в них попадаются ЗОНЫ — `co.cc`, `id.pl`,
`msk.ru`. Одна такая строка превращалась в приговор всему, что под ней
зарегистрировано. Прежний признак («первое слово длиннее трёх букв и не
похоже на зону») отделял их на глаз; здесь отделение точное.

ПОЧЕМУ ИМЕННО ЭТОТ СПИСОК. Он и есть ответ на вопрос «кому принадлежит имя»:
под `co.uk` регистрируется кто угодно, а `bbc.co.uk` принадлежит одному
владельцу. Сами составить такой список нельзя — его ведут сообществом, и в
нём есть то, чего не выведешь правилом: `msk.ru`, `blogspot.com`, `ddns.net`.

ЧТО ЛЕЖИТ РЯДОМ. `core/public_suffix_list.dat` — файл Mozilla как он есть,
байт в байт, вместе с заголовком лицензии MPL 2.0. Не редактировать руками:
обновление — это замена файла целиком с сайта publicsuffix.org.

СКОРОСТЬ. Через очистку проходит КАЖДАЯ строка базы, а в списке больше десяти
тысяч правил. Поэтому наружу отдаются готовые множества, а разбор файла идёт
один раз за процесс. Проверка «эта метка — зона?» стоит одного обращения к
множеству, а не перебора правил.
"""
import os
import threading

__all__ = ["зоны_верхнего_уровня", "публичный_суффикс", "версия_списка",
           "правил_прочитано"]

ФАЙЛ = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                    "public_suffix_list.dat")

_замок = threading.Lock()
_разобрано = None


def _разобрать():
    """Читает файл один раз. Ошибка чтения — пустые множества, а не падение.

    Пустые множества означают, что оба вызывающих места просто вернутся к
    осторожному поведению: очистка не станет резать, фильтр одноразовых не
    станет хоронить поддомены. Уронить разбор базы из-за отсутствующего файла
    нельзя — он поставляемый, но в чужой сборке его может не оказаться.
    """
    правила = set()          # обычные правила: com, co.uk, msk.ru
    подстановки = set()      # правила вида *.ck — суффикс любая метка под ck
    исключения = set()       # правила вида !city.kawasaki.jp — это НЕ суффикс
    зоны = set()             # последние метки всех правил: настоящие TLD
    версия = ""

    def положить(куда, имя):
        """Кладёт имя И его punycode-вид.

        В файле Mozilla интернационализированные зоны записаны БУКВАМИ —
        `рф`, `бг`, `中国`, — а `xn--` в нём не встречается ни разу (проверено
        поиском по файлу: ноль строк). Программа же к этому месту приходит уже
        с punycode: домен переводит `to_ascii_domain` ещё до очистки. Без
        второго вида список молча не знал бы ни одной зоны IDN, и
        `почта.рф` остался бы без той самой защиты, ради которой список и
        заводится.
        """
        куда.add(имя)
        зоны.add(имя.rsplit(".", 1)[-1])
        if not имя.isascii():
            try:
                пуни = имя.encode("idna").decode("ascii")
            except Exception:
                return
            куда.add(пуни)
            зоны.add(пуни.rsplit(".", 1)[-1])

    try:
        with open(ФАЙЛ, encoding="utf-8") as файл:
            for строка in файл:
                текст = строка.strip()
                if not текст:
                    continue
                if текст.startswith("//"):
                    if "VERSION:" in текст and not версия:
                        версия = текст.split("VERSION:", 1)[1].strip()
                    continue
                имя = текст.lower()
                if имя.startswith("!"):
                    положить(исключения, имя[1:])
                elif имя.startswith("*."):
                    положить(подстановки, имя[2:])
                else:
                    положить(правила, имя)
    except Exception:
        return frozenset(), frozenset(), frozenset(), frozenset(), ""
    return (frozenset(правила), frozenset(подстановки), frozenset(исключения),
            frozenset(зоны), версия)


def _данные():
    global _разобрано
    if _разобрано is None:
        with _замок:
            if _разобрано is None:
                _разобрано = _разобрать()
    return _разобрано


def зоны_верхнего_уровня():
    """Все настоящие зоны верхнего уровня: com, ru, deloitte, xn--p1ai.

    Собраны как последние метки ВСЕХ правил списка, поэтому сюда попадает и
    зона, которая в файле встречается только внутри составного правила.
    """
    return _данные()[3]


def публичный_суффикс(имя):
    """True, если имя — ЗОНА, под которой регистрируются посторонние люди.

    `co.uk`, `msk.ru`, `id.pl`, `ddns.net` — да. `bbc.co.uk`, `gmail.com`,
    `mailinator.com` — нет: у них один владелец.

    Разбирает и подстановки (`*.bd`), и исключения (`!city.kawasaki.jp`) — те
    самые случаи, ради которых список и ведут вручную. Мусор на входе — это
    «нет», а не падение: зовут отсюда из рабочих потоков.
    """
    if not isinstance(имя, str):
        return False
    очищенное = имя.strip().lower().rstrip(".")
    if not очищенное:
        return False
    правила, подстановки, исключения, _зоны, _версия = _данные()
    # Исключение сильнее всего: оно затем и написано, чтобы отменить
    # подстановку, под которую имя иначе попало бы.
    if очищенное in исключения:
        return False
    if очищенное in правила:
        return True
    if "." in очищенное:
        родитель = очищенное.split(".", 1)[1]
        if родитель in подстановки:
            return True
    return False


def версия_списка():
    """Дата списка из его собственного заголовка. Для отчётов и проверок."""
    return _данные()[4]


def правил_прочитано():
    """Сколько правил разобрано. Ноль означает, что файл не прочитался."""
    правила, подстановки, исключения, _зоны, _версия = _данные()
    return len(правила) + len(подстановки) + len(исключения)
