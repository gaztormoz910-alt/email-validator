# -*- coding: utf-8 -*-
"""Потоки вывода для программы, у которой их нет.

ЗАЧЕМ. У собранной с `console=False` программы `sys.stdout` и `sys.stderr`
равны None. Пока к ним никто не прикасается, это ещё не беда — беда
начинается, когда поверх пустоты кто-нибудь кладёт обёртку.

Это не теория. Замерено 11.09.2026 на релизе 1.1.8: `webview.OPEN_DIALOG` —
не константа, а свойство модуля, которое при КАЖДОМ обращении пишет
предупреждение об устаревании через `logging`. Обработчика у того логгера
нет, поэтому запись идёт через `logging.lastResort`, а он берёт `sys.stderr`
В МОМЕНТ ЗАПИСИ.

И вот точное место. САМ ПО СЕБЕ None БЕЗОПАСЕН: `handleError` начинается с
`if raiseExceptions and sys.stderr:` и при None молча ничего не делает. Ронял
поток, который ЕСТЬ, но при записи падает, — `StderrFilter(None)` из
`main.py`. `handleError` доходил до `sys.stderr.write`, ловил там только
`OSError`, и `AttributeError` уходил наружу — из логгера, из свойства, из
выбора файла — и доезжал до окна как `choose: 500`. Не работали ВСЕ ЧЕТЫРЕ
диалога: выбор базы, две выгрузки и выбор папки.

Замер (tests/test_nostream.py, отдельный процесс, без перехвата pytest):

    stderr=None          -> НЕ УПАЛО
    stderr=Фильтр(None)  -> AttributeError: 'NoneType' object ... 'write'

Тот же процесс возвращал 120: сбросить сломанные потоки при выходе CPython
тоже не смог. То есть ломалось не только нажатие кнопки, но и сам выход.

Убрать конкретное обращение мало: напечатать что-нибудь может любая чужая
библиотека в любой момент, и программа снова умрёт на ровном месте. Поэтому
потоки здесь заводятся ВСЕГДА, а не затыкается один известный источник.

Куда писать. Если рядом с программой есть куда — пишем в файл: молча терять
чужие сообщения значит остаться без улик, когда что-то пойдёт не так. Если
файл не завести (нет прав, диск полон) — глотаем, но не падаем: вывод в
журнал не стоит того, чтобы из-за него не открылась программа.
"""
import os
import sys


class ТихийПоток:
    """Поток, который всё принимает и ничего не может сломать.

    Нужен как последний рубеж: если и файл не открылся, программа обязана
    работать дальше. Молчание здесь — осознанный размен, а не недосмотр.
    """

    encoding = "utf-8"
    errors = "replace"

    def write(self, текст):
        return len(текст) if isinstance(текст, str) else 0

    def writelines(self, строки):
        for с in строки:
            self.write(с)

    def flush(self):
        pass

    def isatty(self):
        return False

    def fileno(self):
        # Некоторые библиотеки спрашивают дескриптор. Честный отказ лучше
        # выдуманного номера: по выдуманному они начнут писать в чужой файл.
        raise OSError("у этого потока нет дескриптора")

    def close(self):
        pass

    @property
    def closed(self):
        return False


# Потолок журнала чужих сообщений и сколько хвоста оставлять при подрезке.
#
# Без потолка файл растёт без предела: чужая библиотека может писать одно и то
# же по десять раз в секунду, и за ночь такой журнал съест диск. У crash.log
# потолок стоял с самого начала, у этого журнала его не было — мой недосмотр,
# замеченный при сплошной проверке 11.09.2026.
ПОТОЛОК = 1024 * 1024
ОСТАВЛЯТЬ = 256 * 1024


def _подрезать(путь):
    """Оставляет свежий хвост, если файл перерос потолок. Молча.

    Молчание здесь обязательно: журнал существует ради разбора аварий и сам
    стать причиной аварии не имеет права — из-за такой же причины чинится
    весь этот модуль.
    """
    try:
        if os.path.getsize(путь) <= ПОТОЛОК:
            return
        with open(путь, "rb") as файл:
            файл.seek(-ОСТАВЛЯТЬ, os.SEEK_END)
            хвост = файл.read()
        # Первая строка хвоста почти наверняка обрублена посередине — читать
        # её всё равно нельзя, так что выбрасываем целиком.
        ПЕРЕВОД = bytes([10])
        граница = хвост.find(ПЕРЕВОД)
        if 0 <= граница < len(хвост) - 1:
            хвост = хвост[граница + 1:]
        with open(путь, "wb") as файл:
            файл.write(хвост)
    except OSError:
        pass


def _файл_журнала(куда):
    """Открывает файл для чужих сообщений. None, если не вышло."""
    try:
        os.makedirs(куда, exist_ok=True)
        путь = os.path.join(куда, "stdout.log")
        _подрезать(путь)
        return open(путь, "a",
                    encoding="utf-8", errors="replace", buffering=1)
    except OSError:
        return None


def _не_ронять_на_кодировке(поток):
    """Разрешает потоку заменять непечатаемые символы вместо падения.

    ЗАЧЕМ. Отсутствие потока — не единственный способ убить программу
    печатью. Второй — консоль с однобайтовой кодировкой: `print` с любой
    кириллицей даёт `UnicodeEncodeError`, и он точно так же не ловится ничем.

    Замерено 11.09.2026 прямо здесь, при сплошной перепроверке: самотест из
    исходников упал на собственной строке «проба вывода» —
    `UnicodeEncodeError: 'charmap' codec can't encode characters`. То есть
    порок тот же, причина другая.

    Заменять символы честнее, чем падать: сообщение теряет несколько букв,
    зато программа продолжает работать. Обратное — потеря всей работы ради
    точности строки в журнале.
    """
    try:
        поток.reconfigure(errors="replace")
    except Exception:
        # Поток может не уметь reconfigure (не TextIOWrapper) или быть уже
        # отсоединённым. Это не повод отказываться от остального.
        pass


def ensure_streams(куда=None):
    """Даёт процессу потоки вывода, если их нет. Возвращает, что сделано.

    Вызывать НАДО РАНЬШЕ ВСЕХ: логгеры чужих библиотек захватывают
    `sys.stderr` в момент своего импорта, и поток, подставленный позже, до
    них уже не дойдёт.
    """
    сделано = {}
    файл = None
    for имя in ("stdout", "stderr"):
        поток = getattr(sys, имя, None)
        # Проверяем не только None: поток может существовать и при этом не
        # уметь write — тогда он ничем не лучше отсутствующего.
        годен = поток is not None and hasattr(поток, "write")
        if годен:
            _не_ронять_на_кодировке(поток)
            сделано[имя] = "был"
            continue
        if файл is None and куда:
            файл = _файл_журнала(куда)
        замена = файл or ТихийПоток()
        setattr(sys, имя, замена)
        сделано[имя] = "файл" if файл else "тихий"
    return сделано
