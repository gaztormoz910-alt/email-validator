# -*- coding: utf-8 -*-
"""Пути к ресурсам и к пишущимся данным — по-разному в сборке и из исходников.

ДВЕ РАЗНЫЕ ВЕЩИ, КОТОРЫЕ НЕЛЬЗЯ ПУТАТЬ.

`resource_path` — то, что лежит ВНУТРИ сборки и только читается: разметка
окна `ui/web`, файл `VERSION`. В собранном .exe этого нет по относительному
пути: PyInstaller кладёт ресурсы в свою папку, и её адрес известен только
через `sys._MEIPASS`.

`data_path` — то, что программа ПИШЕТ: кэш вердиктов, журнал аварий, долгая
память, настройки, временные таблицы результатов. Класть это в `_MEIPASS`
нельзя ни при каких обстоятельствах: в режиме onefile та папка временная и
стирается при выходе, то есть кэш вердиктов терялся бы каждый запуск.

ПОЧЕМУ `data/` НЕ РЕСУРС, ХОТЯ ЧАСТЬ ЕЁ ПОСТАВЛЯЕТСЯ С ПРОГРАММОЙ. Замерено
по коду: в одной и той же папке лежат поставляемые списки
(`free_providers.txt`, `disposable*.txt`) и то, что пишется на ходу
(`validation_cache.sqlite`, `settings.json`, `crash.log`, `results_*.sqlite`),
причём `BlacklistDownloader` ПЕРЕЗАПИСЫВАЕТ те же самые .txt свежими версиями.
Разделить их на «ресурс» и «данные» нельзя — это один каталог с двумя ролями.

Поэтому `data/` живёт рядом с .exe, а поставляемые списки при первом запуске
копируются туда из сборки, если их там ещё нет (`seed_data`). Без копирования
запуск из `dist/MailFact/MailFact.exe` до установки вёл бы себя иначе, чем
установленная копия, и проверка в CI проверяла бы не то, что получит человек.

Установка идёт в профиль пользователя (%LOCALAPPDATA%/Programs/MailFact)
именно для того, чтобы запись рядом с программой была разрешена без прав
администратора.
"""
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Списки, которые поставляются вместе с программой и должны оказаться в
# пишущейся папке. Дальше их обновляет BlacklistDownloader поверх этих же имён.
ПОСТАВЛЯЕМЫЕ = ("free_providers.txt", "disposable.txt",
                "disposable_extra.txt", "disposable_more.txt")


def is_frozen():
    """True, если мы внутри собранного PyInstaller-ом .exe."""
    return bool(getattr(sys, "frozen", False))


def bundle_dir():
    """Папка, куда PyInstaller распаковал ресурсы. Из исходников — корень."""
    return getattr(sys, "_MEIPASS", ROOT)


def resource_path(*parts):
    """Путь к ЧИТАЕМОМУ ресурсу сборки."""
    return os.path.join(bundle_dir(), *parts)


def app_dir():
    """Папка, рядом с которой программа имеет право писать.

    В сборке это каталог самого .exe, а не `_internal`: человек видит там
    свои данные и может их забрать, а деинсталлятор — удалить.
    """
    if is_frozen():
        return os.path.dirname(os.path.abspath(sys.executable))
    return ROOT


def data_dir():
    """Пишущаяся папка данных. Создаётся при первом обращении."""
    путь = os.path.join(app_dir(), "data")
    try:
        os.makedirs(путь, exist_ok=True)
    except OSError:
        # Права могли не дать. Отдаём путь как есть: тот, кто пишет, получит
        # понятную ошибку на записи, а не молчаливую подмену каталога.
        pass
    return путь


def data_path(*parts):
    """Путь к ПИШУЩЕМУСЯ файлу данных."""
    return os.path.join(data_dir(), *parts)


def seed_data():
    """Копирует поставляемые списки в пишущуюся папку, если их там нет.

    Только недостающие: уже обновлённый на машине пользователя список
    затирать своей поставочной копией нельзя — это откат его данных назад.
    Возвращает имена того, что скопировали.
    """
    if not is_frozen():
        return []
    куда = data_dir()
    скопировано = []
    for имя in ПОСТАВЛЯЕМЫЕ:
        цель = os.path.join(куда, имя)
        if os.path.exists(цель):
            continue
        исток = resource_path("data", имя)
        if not os.path.exists(исток):
            continue
        try:
            shutil.copyfile(исток, цель)
            скопировано.append(имя)
        except OSError:
            # Не смогли — работаем дальше. Списки нужны скорингу, но без них
            # программа обязана открыться и сказать об этом, а не умереть.
            pass
    return скопировано


def app_version():
    """Версия программы. Единственный источник — файл VERSION.

    Читается из сборки: он кладётся туда через `datas`. Разъехаться с тегом
    и со свойствами .exe физически не может, потому что все трое читают
    именно этот файл.
    """
    try:
        with open(resource_path("VERSION"), encoding="utf-8") as f:
            текст = f.read().strip()
        return текст or "0.0.0"
    except OSError:
        return "0.0.0"
