# -*- coding: utf-8 -*-
"""Предохранитель на MX-хост: куда программе ходить НЕЛЬЗЯ.

ЗАЧЕМ. Хозяин любого домена сам пишет свои DNS-записи. Поставив
`MX 0 192.168.1.50`, он указывает адрес ВНУТРИ сети того, кто эту почту
проверяет. Программа туда подключалась и верила ответу — доказано прогоном на
живом коде:

    домен:      zloy-domen.test
    MX:         192.168.1.50        (внутренний адрес)
    подключение → 192.168.1.50:25
    RCPT TO:    kto-ugodno@zloy-domen.test
    ответ:      250 2.1.5 OK
    ВЕРДИКТ:    valid                ← ящика нет нигде

Последствий два, и второе хуже первого. Первое — «Годен» на несуществующем
ящике. Второе — обращение к узлам внутренней сети по указанию постороннего:
на домашней машине это мелочь, на VPS чужой домен сможет заставить валидатор
стучаться в соседние сервисы.

Половину случая уже закрывала тройная проба catch-all: если внутренний сервер
принимает ВСЁ, она это ловит и понижает вердикт. Не закрывала она случай,
когда сервер отвечает избирательно, — а именно так ведёт себя настоящий
почтовик у кого-то внутри сети.

ЧТО ЗДЕСЬ НЕ ДЕЛАЕТСЯ. Вердикт `invalid` по этому признаку не ставится
никогда. Домен с внутренним MX может быть чьей-то настоящей внутренней
почтой; мы просто не можем её проверить снаружи, и честный ответ здесь —
«не проверено», а не «ящика нет».
"""

import ipaddress
import re
import socket

__all__ = ["is_ip_literal", "resolves_to_private", "filter_mx_hosts",
           "REASON_PRIVATE", "REASON_IP_LITERAL"]

REASON_IP_LITERAL = ("MX-запись указывает прямо на IP-адрес вместо имени "
                     "хоста — это нарушение RFC 2181 §10.3, и подключение по "
                     "ней уходит неизвестно куда")
REASON_PRIVATE = ("MX-хост ведёт на внутренний адрес (localhost, приватная "
                  "сеть или зарезервированный диапазон). Снаружи такая почта "
                  "недоступна, а подключаться туда по указанию чужого домена "
                  "нельзя")

_IPV4 = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")


def is_ip_literal(host):
    """MX указывает прямо на адрес, а не на имя хоста.

    RFC 2181 §10.3 требует, чтобы значением MX было ДОМЕННОЕ ИМЯ. Адрес там
    — ошибка настройки, и следовать ей опасно: имя мы бы ещё резолвили через
    свой резолвер, а голый адрес уводит подключение куда сказано.
    """
    if not host or not isinstance(host, str):
        return False
    сырое = host.strip().strip(".").strip("[]")
    if not сырое:
        return False
    # IPv6 в MX встречается как есть, без скобок.
    try:
        ipaddress.ip_address(сырое)
        return True
    except ValueError:
        pass
    return bool(_IPV4.match(сырое))


def _адрес_запрещён(текст):
    try:
        адрес = ipaddress.ip_address(текст)
    except ValueError:
        return False
    return (адрес.is_private or адрес.is_loopback or адрес.is_link_local
            or адрес.is_multicast or адрес.is_reserved
            or _ведёт_в_никуда(адрес))


def _ведёт_в_никуда(адрес):
    """0.0.0.0 и :: — «никуда»: подключение по такому адресу уходит на
    локальный интерфейс. Отдельной функцией, потому что у старых версий
    ipaddress свойства is_unspecified может не быть."""
    try:
        return адрес.is_unspecified
    except AttributeError:
        return str(адрес) in ("0.0.0.0", "::")


def resolves_to_private(host, resolve=None):
    """Ведёт ли имя хоста на внутренний адрес.

    resolve — как узнавать адреса (для тестов). По умолчанию системный
    резолвер: MX-хост это имя в публичном DNS, и спрашивать его через прокси
    незачем — нам нужен не ответ почтовика, а куда указывает запись.

    Возвращает True только при УВЕРЕННОСТИ. Сбой резолвера даёт False:
    запретить проверку из-за собственной неудачи значило бы похоронить
    живые адреса — та же ошибка, от которой защищает весь остальной код.
    """
    if not host or not isinstance(host, str):
        return False
    сырое = host.strip().strip(".")
    if is_ip_literal(сырое):
        return _адрес_запрещён(сырое.strip("[]"))

    получить = resolve or _системный_резолвер
    try:
        адреса = получить(сырое)
    except Exception:
        return False
    if not адреса:
        return False
    # Хватает ОДНОГО внутреннего адреса: если имя резолвится и туда, и
    # наружу, подключение может уйти именно внутрь.
    return any(_адрес_запрещён(а) for а in адреса)


def _системный_резолвер(host):
    сведения = socket.getaddrinfo(host, None)
    return [запись[4][0] for запись in сведения]


def filter_mx_hosts(hosts, resolve=None):
    """Оставляет только те MX, к которым идти можно.

    Возвращает (годные, отвергнутые) — второе списком пар (хост, причина),
    чтобы владелец увидел в логе, ЧТО именно отброшено и почему. Молчаливое
    отбрасывание здесь недопустимо: это выглядело бы как «у домена нет MX».
    """
    годные, отвергнутые = [], []
    for хост in (hosts or []):
        if is_ip_literal(хост):
            отвергнутые.append((хост, REASON_IP_LITERAL))
            continue
        if resolves_to_private(хост, resolve=resolve):
            отвергнутые.append((хост, REASON_PRIVATE))
            continue
        годные.append(хост)
    return годные, отвергнутые
