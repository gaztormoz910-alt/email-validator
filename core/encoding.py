# core/encoding.py
"""Определение кодировки входного файла.

Зачем это отдельно. Базы приходят откуда угодно: выгрузка из Excel — это
Windows-1251, экспорт из старой CRM — UTF-16, файл из блокнота — UTF-8 с
меткой в начале. Раньше все они открывались одинаково:

    open(path, "r", encoding="utf-8", errors="ignore")

и это молча портило данные. `errors="ignore"` не сообщает об ошибке — он
ВЫБРАСЫВАЕТ байты, которые не разобрались. Кириллица в Windows-1251 состоит
как раз из таких байтов, поэтому `анна@mail.ru` превращался в `@mail.ru`:
адрес с пустой локальной частью, который дальше отбраковывался по синтаксису.
Владелец видел «невалидный адрес» и не мог узнать, что виноват не адрес.

С UTF-16 хуже: там каждый символ занимает два байта, и при чтении как UTF-8
между буквами появляются нулевые байты. Ни один адрес не проходит проверку,
и теряется файл целиком.

Порядок определения — от надёжного к вероятному:

  1. метка в начале файла (BOM) — однозначный ответ, если она есть;
  2. нулевые байты в выборке — признак UTF-16 без метки;
  3. строгая проверка на UTF-8: она почти не даёт ложных срабатываний,
     потому что случайные байты редко складываются в правильную
     последовательность;
  4. Windows-1251 как запасной вариант: у русскоязычных баз это самая частая
     кодировка после UTF-8.
"""
import io

__all__ = ["detect_encoding", "open_text", "read_sample"]

# Сколько байт достаточно для опознания. Кодировка не меняется по ходу файла,
# а читать гигабайтную базу ради ответа на этот вопрос незачем.
SAMPLE_BYTES = 65536

# Запасная кодировка. Для русскоязычных баз это Windows-1251: именно в неё
# сохраняет Excel, и именно она приходит с форумов и из старых выгрузок.
FALLBACK_ENCODING = "cp1251"

# Имена с «-sig» и голые «utf-16»/«utf-32» выбраны намеренно: этим кодекам
# Python скармливает метку сам и убирает её из текста. Возьми мы utf-16-le,
# метка осталась бы первым символом первой строки — и первый адрес файла
# приехал бы с невидимым мусором в начале.
_BOMS = (
    (b"\xef\xbb\xbf", "utf-8-sig"),
    (b"\xff\xfe\x00\x00", "utf-32"),
    (b"\x00\x00\xfe\xff", "utf-32"),
    (b"\xff\xfe", "utf-16"),
    (b"\xfe\xff", "utf-16"),
)


def read_sample(path, size=SAMPLE_BYTES):
    """Первые байты файла. Пустой ответ, если файл недоступен."""
    try:
        with io.open(path, "rb") as handle:
            return handle.read(size)
    except OSError:
        return b""


def detect_encoding(path):
    """Кодировка файла именем, пригодным для io.open.

    Никогда не возвращает None: не сумев определить, отвечает запасной
    кодировкой. Чтение важнее точности определения — файл, который не
    открылся, теряется целиком.
    """
    sample = read_sample(path)
    if not sample:
        return "utf-8"

    for bom, name in _BOMS:
        if sample.startswith(bom):
            return name

    # UTF-16 без метки. У латиницы и цифр старший байт нулевой, поэтому в
    # тексте они попадаются через один. Проверяем обе половины: нули на
    # чётных позициях — big-endian, на нечётных — little-endian.
    zeros_even = sample[0::2].count(0)
    zeros_odd = sample[1::2].count(0)
    half = max(1, len(sample) // 2)
    if zeros_odd > half * 0.3 and zeros_even < half * 0.05:
        return "utf-16-le"
    if zeros_even > half * 0.3 and zeros_odd < half * 0.05:
        return "utf-16-be"

    # Строгая проверка на UTF-8. Обрезанный на границе символа хвост выборки
    # не должен считаться ошибкой, поэтому пробуем отбросить до трёх байт.
    for cut in (0, 1, 2, 3):
        chunk = sample[:len(sample) - cut] if cut else sample
        try:
            chunk.decode("utf-8")
            return "utf-8"
        except UnicodeDecodeError:
            continue

    return FALLBACK_ENCODING


def open_text(path, encoding=None):
    """Открывает текстовый файл в правильной кодировке.

    errors="replace", а не "ignore": испорченный байт должен оставить след в
    строке, а не исчезнуть. Исчезнувший байт превращает `анна@mail.ru` в
    `@mail.ru` — внешне правильный адрес, который на самом деле чужой.
    """
    return io.open(path, "r", encoding=encoding or detect_encoding(path),
                   errors="replace")
