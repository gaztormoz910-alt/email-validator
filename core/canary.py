# -*- coding: utf-8 -*-
"""Канарейки: заведомо мёртвые адреса, которыми ловят врущий почтовик.

ЗАЧЕМ, ЕСЛИ КОНТРОЛЬНАЯ ПРОБА УЖЕ ЕСТЬ. Контрольная проба спрашивает
выдуманный адрес В ТОЙ ЖЕ СЕССИИ, где сервер только что сказал `250` на
настоящий. Она ловит catch-all — постоянное свойство домена. Но есть два
случая, которых она не видит:

  * **тарпитинг включился посреди прогона.** Первые двести адресов домена
    проверены честно, на двести первом почтовик решил, что с нашего выхода
    идёт перебор, и начал принимать любого получателя. Всё, что после, —
    сплошные `Valid`, и ни один не значит ничего;
  * **у гигантов контрольная проба идёт не всегда.** Для gmail.com, Yahoo,
    Outlook и iCloud catch-all невозможен по устройству, поэтому проба там
    стоит ради тарпитинга и включается раз в 25 адресов на домен. В зазоре
    между двумя её срабатываниями врущий сервер не виден.

Канарейка закрывает оба: это отдельная проба отдельным адресом, которого
заведомо не существует, и вернувшийся на неё `250` означает, что ЭТОТ выход
на ЭТОМ домене врёт ПРЯМО СЕЙЧАС.

ЧТО С ЭТИМ ДЕЛАТЬ. Не выбрасывать адреса — это была бы обратная ошибка, и
живые контакты уехали бы в мусор из-за нашего же прокси. Правильный ответ:
пометить все `Valid`, полученные с этой пары «выход + домен» в этом прогоне,
как недоказуемые, и сказать владельцу, что виноват прокси, а не база.

ПОЧЕМУ АДРЕС ЗАВЕДОМО МЁРТВ. Локальная часть собирается из случайных 24
знаков плюс метка `-canary-`. Вероятность, что такой ящик существует, ниже
вероятности отказа оборудования; при этом он остаётся синтаксически законным
(RFC 5321 §4.5.3.1: не длиннее 64 октетов), иначе сервер отверг бы его по
форме, а не по отсутствию получателя, и проба не значила бы ничего.

ЦЕНА. Одна лишняя сессия на домен за прогон при пороге по умолчанию. На базе
владельца (5000 адресов, 188 доменов) это 188 сессий против 5000 основных —
меньше четырёх процентов.
"""

import secrets
import threading

__all__ = ["CanaryWatch", "canary_address", "CANARY_MARK"]

# Метка в адресе. Нужна не программе, а человеку: увидев такой адрес в чужом
# логе, почтмейстер поймёт, что это проба существования, а не попытка
# доставки. Скрывать её незачем — врущий сервер отвечает `250` всем подряд и
# в текст не смотрит.
CANARY_MARK = "-canary-"

# Сколько знаков случайности. 24 знака из 32-значного алфавита — это больше
# 10^36 вариантов; совпадение с живым ящиком невозможно на любом мыслимом
# объёме баз.
_ДЛИНА = 24
_АЛФАВИТ = "abcdefghijkmnopqrstuvwxyz23456789"


def canary_address(domain):
    """Синтаксически законный адрес, которого заведомо не существует."""
    хвост = "".join(secrets.choice(_АЛФАВИТ) for _ in range(_ДЛИНА))
    local = "zz" + CANARY_MARK + хвост
    # Проверка на всякий случай: предел RFC 5321 §4.5.3.1 — 64 октета.
    # Если кто-то удлинит метку, обрежемся здесь, а не получим отказ по форме
    # и ложный вывод «сервер отвечает честно».
    return "%s@%s" % (local[:64], domain)


class CanaryWatch(object):
    """Кто из выходов врёт, на каком домене и с какого момента.

    Состояние живёт один прогон. Между запусками его хранить нельзя: врущим
    выход становится не навсегда, а на время — почтовик отпускает подозрение
    сам. Запомнив это на сутки, мы повторили бы дефект Б4, где тарпитинг
    оседал в долгой памяти и хоронил всю почту gmail на месяц.
    """

    def __init__(self, every=1, min_valid=1):
        """every — раз во сколько ПРОВЕРЕННЫХ адресов домена пускать канарейку.

        По умолчанию 1: одна проба на пару «выход + домен» за прогон, и
        больше на этой паре не тратимся, пока она честна. min_valid — сколько
        Valid должно набраться, прежде чем проверять: канарейка нужна там,
        где есть что защищать.
        """
        self.every = max(1, int(every))
        self.min_valid = max(1, int(min_valid))
        self._lock = threading.Lock()
        # (выход, домен) -> сколько Valid насчитали
        self._valid = {}
        # (выход, домен) -> проверено ли уже
        self._probed = set()
        # (выход, домен) -> врёт
        self._врут = set()
        # Сколько раз канарейка сработала. Для отчёта владельцу.
        self.поймано = 0
        self.проб = 0

    # ── учёт ────────────────────────────────────────────────────────────

    @staticmethod
    def _пара(exit_ip, domain):
        return (str(exit_ip or "прямое соединение").lower(),
                str(domain or "").lower())

    def note_valid(self, exit_ip, domain):
        """Отметить, что с этого выхода на этом домене получен Valid."""
        ключ = self._пара(exit_ip, domain)
        with self._lock:
            self._valid[ключ] = self._valid.get(ключ, 0) + 1
            return self._valid[ключ]

    def should_probe(self, exit_ip, domain):
        """Пора ли пускать канарейку на эту пару.

        Дважды на одной паре не тратимся: если выход честен, повторная проба
        ничего не добавит, а лишняя сессия к чужому почтовику — это лишний
        повод попасться ему на глаза.
        """
        ключ = self._пара(exit_ip, domain)
        with self._lock:
            if ключ in self._probed or ключ in self._врут:
                return False
            набрано = self._valid.get(ключ, 0)
            if набрано < self.min_valid:
                return False
            return набрано % self.every == 0

    def record(self, exit_ip, domain, status):
        """Записать ответ на канарейку. True, если выход уличён.

        Уличает ТОЛЬКО `valid` и `catchall`. Всё остальное — включая отказ,
        таймаут и серый список — означает, что проба не удалась либо сервер
        ответил честно; ни то ни другое не повод сомневаться в Valid.
        """
        ключ = self._пара(exit_ip, domain)
        врёт = str(status or "").lower() in ("valid", "catchall")
        with self._lock:
            self._probed.add(ключ)
            self.проб += 1
            if врёт:
                self._врут.add(ключ)
                self.поймано += 1
        return врёт

    # ── вопросы ─────────────────────────────────────────────────────────

    def is_compromised(self, exit_ip, domain):
        """Врёт ли этот выход на этом домене."""
        with self._lock:
            return self._пара(exit_ip, domain) in self._врут

    def compromised_domains(self):
        """Домены, где хоть один выход уличён. Для пересмотра строк."""
        with self._lock:
            return sorted({домен for _выход, домен in self._врут})

    def summary(self):
        """Короткий отчёт для лога владельца."""
        with self._lock:
            return {"проб": self.проб, "поймано": self.поймано,
                    "домены": sorted({d for _e, d in self._врут})}
