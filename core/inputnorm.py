# -*- coding: utf-8 -*-
"""Приведение входной строки к виду, в котором адрес вообще можно проверить.

Шесть починок, каждая найдена сверкой с чужими каталогами критериев и
замерена на этом коде до правки:

    1.3   невидимый знак ВНУТРИ адреса переживал очистку (снимались только края)
    1.7   знак смены направления U+202E — то же самое
    1.8   полноширинные знаки отвергались синтаксисом: живой gmail, набранный
          в японской или китайской раскладке, хоронился без запроса в сеть
    3.25  полноширинная точка в домене, наоборот, ПРИНИМАЛАСЬ — а DNS такого
          домена не найдёт, и адрес уезжал в «мёртвый домен»
    1.9   две формы Unicode одного адреса считались разными ящиками
    1.13  URL-кодированный адрес не раскодировался
    1.14  HTML-сущности не раскодировались

ГРАНИЦА, КОТОРУЮ ЗДЕСЬ НЕЛЬЗЯ ПЕРЕХОДИТЬ. Владелец запрещал переписывать его
данные, и запрет остаётся в силе. Разница между починкой и подменой такая:

    ПОЧИНКА — знак невидим, или это тот же знак в другой кодировке, или
              форма записи, которую требует сам протокол. Строка после неё
              адресует ТОТ ЖЕ ящик;
    ПОДМЕНА — строка начинает адресовать ДРУГОЙ ящик. Здесь такого нет и
              быть не должно.

Исходная строка при этом всё равно доезжает до выгрузки колонкой
`OriginalEmail` — чтобы владелец видел, что именно он загружал.
"""

import html as _html
import re
import unicodedata
import urllib.parse

__all__ = ["strip_invisible", "fold_fullwidth", "to_nfc", "decode_wrappers",
           "normalize_input", "split_addresses", "INVISIBLE"]

# Знаки, которых на экране нет. Внутри адреса они меняют строку, не меняя её
# вида, — и мы спрашиваем у сервера НЕ ТОТ ящик, получая 550 на живом адресе.
INVISIBLE = (
    "​‌‍⁠﻿"      # нулевой ширины и BOM
    "‎‏"                          # метки направления
    "‪‫‬‭‮"       # встраивание и переопределение
    "⁦⁧⁨⁩"             # изоляты
    "­"                                # мягкий перенос
)
_НЕВИДИМЫЕ = {ord(з): None for з in INVISIBLE}

# Полноширинные формы: U+FF01..U+FF5E повторяют ASCII 0x21..0x7E со сдвигом.
# Отдельно U+3000 — полноширинный пробел.
_СДВИГ = 0xFF01 - 0x21


def strip_invisible(text):
    """Снимает невидимые знаки по ВСЕЙ строке, а не только по краям."""
    if not isinstance(text, str):
        return text
    return text.translate(_НЕВИДИМЫЕ)


def fold_fullwidth(text):
    """Полноширинные знаки -> обычные. `ｉｖａｎ＠ｇｍａｉｌ．ｃｏｍ` -> `ivan@gmail.com`.

    Это ОДИН И ТОТ ЖЕ знак в другой кодировке, а не другой адрес: так пишет
    любая японская, китайская или корейская раскладка. Правило узкое — только
    диапазон, который однозначно отображается в ASCII. Кириллица, умляуты и
    прочее не-ASCII не трогаются вовсе: они значащие.
    """
    if not isinstance(text, str):
        return text
    вышло = []
    for знак in text:
        код = ord(знак)
        if 0xFF01 <= код <= 0xFF5E:
            вышло.append(chr(код - _СДВИГ))
        elif код == 0x3000:
            вышло.append(" ")
        else:
            вышло.append(знак)
    return "".join(вышло)


def to_nfc(text):
    """Каноническая форма Unicode.

    `é` записывается двумя способами: готовой буквой U+00E9 и парой
    «e + комбинирующий акут». На экране одно и то же, в байтах разное — и
    один и тот же ящик уходил в сеть двумя адресами, из которых один получал
    550. RFC 6532 §3.1 прямо требует NFC для интернационализированных
    адресов, так что это форма протокола, а не наша выдумка.
    """
    if not isinstance(text, str):
        return text
    try:
        return unicodedata.normalize("NFC", text)
    except Exception:
        return text


_ПРОЦЕНТ = re.compile(r"%[0-9A-Fa-f]{2}")
_СУЩНОСТЬ = re.compile(r"&(#\d{2,5}|#x[0-9A-Fa-f]{2,4}|[a-zA-Z]{2,8});")


def decode_wrappers(text):
    """Раскрывает URL-кодировку и HTML-сущности — ТОЛЬКО если стало лучше.

    `ivan%40gmail.com` и `ivan&#64;gmail.com` — это адреса, скопированные со
    страницы или из журнала. Без раскрытия они остаются мусором.

    «Стало лучше» проверяется буквально: в исходной строке собаки не было, а
    после раскрытия появилась ровно одна. Без этого условия правило сломало
    бы законные адреса: `%` входит в atext по RFC 5322 §3.2.3, и
    `a%b@corp.com` — нормальный ящик, который раскрывать нельзя.
    """
    if not isinstance(text, str) or "@" in text:
        return text

    for раскрыть, образец in ((urllib.parse.unquote, _ПРОЦЕНТ),
                              (_html.unescape, _СУЩНОСТЬ)):
        if not образец.search(text):
            continue
        try:
            вышло = раскрыть(text)
        except Exception:
            continue
        if вышло.count("@") == 1:
            return вышло
    return text


def normalize_input(text):
    """Весь порядок целиком. Порядок шагов важен и выбран не случайно.

    Сначала невидимые знаки: пока они внутри, любое сравнение и любой разбор
    работают с не той строкой. Потом полноширинные — иначе `＠` не будет
    опознана как собака, и раскрытие кодировки решит, что собаки нет. Потом
    NFC. Раскрытие кодировки — последним, потому что оно смотрит, есть ли
    собака, и до предыдущих шагов ответ на это может быть неверным.
    """
    if not isinstance(text, str):
        return text
    вышло = strip_invisible(text)
    вышло = fold_fullwidth(вышло)
    вышло = to_nfc(вышло)
    return decode_wrappers(вышло)


# Адрес в строке: имя ящика, собака, домен с точкой. Края обрежет очистка,
# поэтому здесь важна не строгость, а то, чтобы НИ ОДИН адрес не пропал.
_АДРЕС = re.compile(
    r"[^\s,;<>()\[\]{}\"]+@[^\s,;<>()\[\]{}\"]+\.[^\s,;<>()\[\]{}\"]+")


def split_addresses(line):
    """ВСЕ адреса из строки, а не первый.

    Замерено до правки: «a@x.com, b@y.com» давало только `a@x.com` — второй
    адрес исчезал молча. Это хуже ложного Invalid: адрес не назван мёртвым,
    он просто пропадает, и инвариант «подано = выдано» этого не замечает —
    он считает то, что загрузчик отдал.

    Одиночный адрес возвращается как есть, целиком: разрезать его нельзя.
    """
    if not isinstance(line, str) or "@" not in line:
        return [line] if isinstance(line, str) and line.strip() else []
    найдено = _АДРЕС.findall(line)
    if len(найдено) <= 1:
        # Ноль или один — отдаём исходную строку: у неё края обрежет очистка,
        # и она может быть в форме «Имя <адрес>» или в кавычках, которую
        # образец выше нарочно не разбирает.
        return [line]
    return найдено
