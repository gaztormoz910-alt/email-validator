# -*- coding: utf-8 -*-
"""Отметки времени на запуске программы: `MailFact.exe --timing ФАЙЛ`.

ЗАЧЕМ. Владелец сказал: «кликаю по иконке — запускается через полминуты».
Замерено снаружи: до появления окна 24.2 и 24.0 секунды, а тот же .exe с
ключом `--version` выходит за 1.0 с. То есть двадцать три секунды из двадцати
четырёх лежат ВНУТРИ запуска, и снаружи не видно, где именно.

Разбирать такое догадками особенно накладно: каждая проверка стоит пересборки
в десять минут. Поэтому здесь постоянный инструмент, а не разовый костыль —
в следующий раз разбор займёт минуту.

ЧЕГО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Пока запись не включена, `отметить` стоит одно
сравнение с None и возврат. Замер, который сам замедляет программу, — это не
замер, а ещё одна причина медленного запуска.
"""
import io
import os
import time

# Список отметок (имя, секунда от старта). None означает «не пишем».
_отметки = None
_начало = None


def включить(момент_старта=None):
    """Включает запись. Момент старта — как можно раньше в main.py.

    Отдельным вызовом, а не автоматически: при обычном запуске программы
    ничего не пишется вовсе.
    """
    global _отметки, _начало
    _начало = момент_старта if момент_старта is not None else time.perf_counter()
    _отметки = []


def включено():
    return _отметки is not None


def отметить(имя):
    """Записывает, сколько секунд прошло от старта до этого места."""
    if _отметки is None:
        return
    _отметки.append((имя, time.perf_counter() - _начало))


def записать(путь):
    """Кладёт отметки в файл. Возвращает секунды до последней отметки.

    Формат — по одной отметке в строке: сколько прошло ОТ СТАРТА и сколько
    заняло ИМЕННО ЭТО место. Второе важнее: суммарное время растёт всегда, а
    виноват один шаг, и в столбце разниц он виден сразу.

    Печатать нельзя: у сборки с console=False потоков вывода нет.
    """
    if not _отметки:
        return 0.0
    каталог = os.path.dirname(os.path.abspath(путь))
    if каталог:
        os.makedirs(каталог, exist_ok=True)
    строки = ["MailFact: отметки запуска", ""]
    строки.append("%-34s %9s %9s" % ("шаг", "от старта", "сам шаг"))
    прошлое = 0.0
    самый = ("", 0.0)
    for имя, когда in _отметки:
        шаг = когда - прошлое
        if шаг > самый[1]:
            самый = (имя, шаг)
        строки.append("%-34s %8.2f с %8.2f с" % (имя, когда, шаг))
        прошлое = когда
    строки.append("")
    строки.append("ВСЕГО: %.2f с" % прошлое)
    строки.append("САМЫЙ ДОЛГИЙ ШАГ: %s — %.2f с" % (самый[0], самый[1]))
    строки.append("TIMING_OK")
    with io.open(путь, "w", encoding="utf-8", newline="") as файл:
        файл.write(chr(10).join(строки) + chr(10))
    return прошлое
