def _увести_данные_во_временную_папку():
    """Набор пишет во ВРЕМЕННУЮ data/, а не в рабочую папку владельца.

    Зачем это делается здесь и прямо на импорте. Модули ядра считают свои
    пути в момент импорта — `core/runstate.py` заводит DEFAULT_STATE_PATH,
    `core/cache.py` DEFAULT_CACHE_PATH, и так далее. Подмена, сделанная в
    фикстуре, опоздала бы: константы к тому времени уже посчитаны. conftest
    импортируется раньше всех тестовых модулей, и это единственная точка,
    где успеваем.

    Что копируется. Поставляемые СПИСКИ (одноразовые домены, бесплатные
    провайдеры) тесты читают, и без них часть проверок теряет смысл — их
    переносим. Пишущиеся артефакты прошлых прогонов (`*.sqlite`, журналы,
    настройки) НЕ переносим намеренно: именно они делали набор зависимым от
    вчерашнего состояния. Тест, которому нужна база или настройки, обязан
    завести их сам.

    Переменная уважается, если её уже выставили снаружи: это позволяет
    прогнать набор на нужной папке, не трогая код.
    """
    if os.environ.get("MAILFACT_DATA_DIR"):
        return
    временная = tempfile.mkdtemp(prefix="mailfact-tests-data-")
    исток = os.path.join(КОРЕНЬ, "data")
    ПИШУЩИЕСЯ = (".sqlite", ".sqlite-shm", ".sqlite-wal", ".log")
    if os.path.isdir(исток):
        for имя in os.listdir(исток):
            путь = os.path.join(исток, имя)
            if os.path.isdir(путь):
                shutil.copytree(путь, os.path.join(временная, имя),
                                dirs_exist_ok=True)
                continue
            if имя.endswith(ПИШУЩИЕСЯ) or имя.startswith("results_"):
                continue
            if имя == "settings.json":
                # Настройки владельца меняют поведение проверок (пороги,
                # «хватит живых прокси»). Набор обязан идти на умолчаниях,
                # иначе его зелёный цвет зависит от галочек в его окне.
                continue
            try:
                shutil.copyfile(путь, os.path.join(временная, имя))
            except OSError:
                pass
    os.environ["MAILFACT_DATA_DIR"] = временная


_увести_данные_во_временную_папку()


