@pytest.fixture(scope="session", autouse=True)
def _закрыть_хранилища_результатов():
    """Закрывает хранилища, которые тесты оставили открытыми.

    ЗАЧЕМ. ResultStore заводит себе временный файл results_*.sqlite и удаляет
    его в close(). Тесты создают хранилища шестнадцатью способами — напрямую и
    внутри ValidatorApi — и почти нигде не закрывают. Замерено 11.09.2026:
    один полный прогон оставлял в data/ по 137 файлов, а собственная уборка
    хранилища трогает только то, чему больше суток.

    ПОЧЕМУ ОДНОЙ ЛОВУШКОЙ, А НЕ ПРАВКОЙ ШЕСТНАДЦАТИ МЕСТ. Правка шестнадцати
    мест чинит сегодняшний мусор и оставляет грабли: семнадцатый тест напишут
    так же. Здесь закрывается всё, что было создано за прогон, кем бы оно ни
    создавалось.

    ПОЧЕМУ НА КОНЕЦ ПРОГОНА, А НЕ КАЖДОГО ТЕСТА. Часть хранилищ живёт в
    модульных заготовках (tests/test_scale_speed.py) и нужна нескольким
    проверкам подряд. Закрытие после каждой из них сломало бы соседние.

    Продукт при этом не тронут: close() уже умеет убирать за собой, ловушка
    лишь следит, чтобы его позвали.
    """
    import os
    import weakref

    from ui.result_store import ResultStore

    # Запоминаем И ссылку, И путь. Одной ссылки мало: брошенное хранилище
    # собирает сборщик мусора, слабая ссылка умирает, close() позвать уже не у
    # кого — а файл остаётся. Замерено 11.09.2026: только на ссылках уборка
    # оставляла 35 файлов из 137.
    записи = []
    исходный = ResultStore.__init__

    def запомнить(self, *args, **kwargs):
        исходный(self, *args, **kwargs)
        if getattr(self, "_temporary", False):
            записи.append((weakref.ref(self), getattr(self, "_path", None)))

    ResultStore.__init__ = запомнить
    try:
        yield
    finally:
        ResultStore.__init__ = исходный
        for ссылка, путь in записи:
            хранилище = ссылка()
            if хранилище is not None:
                try:
                    хранилище.close()
                except Exception:
                    # Уборка не имеет права уронить прогон: её дело — не
                    # оставить мусора, а не решать судьбу результата тестов.
                    pass
            if not путь:
                continue
            # Досюда доходит только то, что хранилище само не убрало: либо его
            # уже не существует, либо close() не дошёл до файла.
            for хвост in ("", "-wal", "-shm"):
                try:
                    os.remove(путь + хвост)
                except OSError:
                    pass


