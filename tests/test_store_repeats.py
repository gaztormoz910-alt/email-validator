# -*- coding: utf-8 -*-
"""Хранилище не показывает один ящик дважды.

ПОЧЕМУ ЭТОТ ФАЙЛ ПОЯВИЛСЯ ТОЛЬКО СЕЙЧАС. Защита в `ResultStore._already_shown`
написана давно, и на неё ссылался гейт из ledger-а accuracy-and-table. Но
команда того гейта звала `tests/test_duplicates.py`, а такого файла в проекте
нет — его переименовали и слили ещё раньше. То есть гейт был не «почти
зелёный», он был неисполним, а поведение — не покрыто ничем.

ЧТО ИМЕННО СТОРОЖИТСЯ. Дедупликацию входа делает конвейер. Это пояс поверх
подтяжек: если результат по одному адресу придёт дважды по любой другой
причине, владелец увидит один ящик двумя строками — то есть предложение
отправить письмо дважды. Жалоба на спам стоит дороже одного лишнего поиска по
индексу.

К каждой проверке приложен ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ с выключенной защитой: без
него зелёный тест не отличить от теста, который не умеет видеть вторую строку.
"""
import os
import sys
import unittest

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)

from ui.result_store import ResultStore  # noqa: E402

ДАННЫЕ = {"engagement_score": 70, "name": "Ivan Petrov", "gender": "male",
          "country": "RU", "provider": "Gmail"}


def положить(хранилище, адрес, статус="Valid"):
    return хранилище.append(адрес, статус, "250 OK", "mx.example.com", ДАННЫЕ)


class TestПовторНеСоздаётВторуюСтроку(unittest.TestCase):
    """С включённой защитой второй результат по тому же ящику отбрасывается."""

    def setUp(self):
        self.хранилище = ResultStore(drop_repeats=True)
        self.addCleanup(self.хранилище.close)

    def всего(self):
        """Число СТРОК.

        Не `sum(counts().values())`: в счётчиках есть ещё `total` и `names`,
        и сумма считает одни и те же строки трижды. Ровно на этом попался
        самотест программы — печатал вшестеро больше, чем положил.
        """
        return self.хранилище.counts()["total"]

    def test_один_и_тот_же_адрес_ложится_один_раз(self):
        положить(self.хранилище, "ivan@gmail.com")
        положить(self.хранилище, "ivan@gmail.com")
        self.assertEqual(self.всего(), 1)

    def test_повтор_возвращает_прежнюю_группу(self):
        """Отбрасывание не должно выглядеть как «адрес пропал».

        Вызывающий обновляет счётчики по возвращённой группе; вернуть здесь
        None значило бы сломать их ради дедупликации.
        """
        первая = положить(self.хранилище, "ivan@gmail.com", "Valid")
        вторая = положить(self.хранилище, "ivan@gmail.com", "Invalid")
        self.assertEqual(вторая, первая)

    def test_регистр_и_пробелы_не_создают_нового_ящика(self):
        """Ключ сравнения — приведённый, иначе защита обходится пробелом."""
        положить(self.хранилище, "ivan@gmail.com")
        положить(self.хранилище, "  IVAN@Gmail.com  ")
        self.assertEqual(self.всего(), 1)

    def test_разные_адреса_не_склеиваются(self):
        """Обратная сторона: защита не имеет права терять РАЗНЫЕ ящики.

        Проверка, которая схлопывает всё подряд, «дублей» не покажет никогда
        и будет зелёной на полностью сломанном хранилище.
        """
        положить(self.хранилище, "ivan@gmail.com")
        положить(self.хранилище, "anna@gmail.com")
        положить(self.хранилище, "ivan@yandex.ru")
        self.assertEqual(self.всего(), 3)

    def test_повтор_после_сброса_на_диск_тоже_виден(self):
        """Ящик, уже уехавший в файл, обязан узнаваться.

        Память о показанных ключах не бесконечна; если бы узнавание работало
        только по ней, на большой базе защита молча переставала бы работать
        ровно тогда, когда она нужнее всего.
        """
        положить(self.хранилище, "ivan@gmail.com")
        self.хранилище._flush_locked()
        положить(self.хранилище, "ivan@gmail.com")
        self.assertEqual(self.всего(), 1)


class TestКонтрольЗащитуВидно(unittest.TestCase):
    """ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: с выключенной защитой вторая строка ПОЯВЛЯЕТСЯ.

    Без него проверки выше были бы зелёными и в том случае, если бы
    хранилище просто перестало принимать второй append по любой причине.
    """

    def test_без_защиты_адрес_ложится_дважды(self):
        хранилище = ResultStore(drop_repeats=False)
        try:
            положить(хранилище, "ivan@gmail.com")
            положить(хранилище, "ivan@gmail.com")
            self.assertEqual(хранилище.counts()["total"], 2)
        finally:
            хранилище.close()

    def test_защита_по_умолчанию_выключена(self):
        """Замер, а не догадка: значение по умолчанию — часть договора.

        Если бы оно молча сменилось, прежние места вызова начали бы терять
        строки, и заметить это было бы нечем.
        """
        хранилище = ResultStore()
        try:
            self.assertFalse(хранилище._drop_repeats)
        finally:
            хранилище.close()


if __name__ == "__main__":
    unittest.main()
