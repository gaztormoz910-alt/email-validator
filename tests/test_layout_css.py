# -*- coding: utf-8 -*-
"""Рабочая область не бывает ростом во всё окно — иначе низ уезжает за экран.

ЧТО СТОРОЖИТСЯ И ПОЧЕМУ. Шапка программы лежит ВНЕ рабочей области и занимает
`--topbar-h` (60 px). Значит, области достаётся высота окна МИНУС шапка.
Базовое правило это учитывает:

    .layout { height: calc(100% - var(--topbar-h)); }

Дважды это правило переписывали в медиазапросах на `height: 100%` — в «узком
окне» и в «низком окне». Сто процентов считаются от body, то есть от всего
окна: область начиналась на 60 px ниже шапки и была ростом во всё окно, и её
собственный низ оказывался на 60 px НИЖЕ края экрана. Прокрутка доезжала до
конца контейнера честно, но последняя полоса контейнера лежала за экраном, и
достать её было нечем. Владелец описал это как «скролл заканчивается раньше,
чем должен».

ПОЧЕМУ ТЕКСТОВАЯ ПРОВЕРКА, ЕСЛИ ЕСТЬ БРАУЗЕРНАЯ. Браузерная (гейт R1 в
`.unlazy/scroll/`) меряет настоящее поведение и сильнее — но ей нужен
playwright с Chromium, которого нет в CI. Эта ловит тот же возврат дёшево и
на всех трёх системах. Одна без другой неполна: текст правила не доказывает
поведение, а браузер не запускается там, где собирается релиз.
"""
import io
import os
import re
import unittest

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
СТИЛИ = os.path.join(КОРЕНЬ, "ui", "web", "style.css")

# Значения, означающие «во всю высоту окна». Для `.layout` любое из них —
# дефект: шапка не вычтена.
ВО_ВСЁ_ОКНО = re.compile(r"^(100%|100vh|100dvh|100svh|100lvh)$", re.I)


def без_комментариев(текст):
    return re.sub(r"/\*.*?\*/", "", текст, flags=re.S)


def правила(css):
    """Разбор на (селектор, тело). Вложенные @media разворачиваются.

    Написано счётчиком скобок, а не регуляркой: медиазапрос — это блок внутри
    блока, и регулярка на нём либо схлопывает вложенность, либо молча
    пропускает половину файла.
    """
    css = без_комментариев(css)
    итог, буфер, глубина, стек = [], "", 0, []
    for ch in css:
        if ch == "{":
            глубина += 1
            стек.append(буфер.strip())
            буфер = ""
        elif ch == "}":
            глубина -= 1
            сел = стек.pop() if стек else ""
            if not сел.startswith("@"):
                итог.append((сел, буфер))
            буфер = ""
        else:
            буфер += ch
    return итог


def нарушения(css):
    """Правила для .layout, задающие высоту во всё окно."""
    найдено = []
    for сел, тело in правила(css):
        if not re.search(r"(^|[\s,>+~])\.layout(?![\w-])", сел):
            continue
        for объявление in тело.split(";"):
            if ":" not in объявление:
                continue
            имя, _, значение = объявление.partition(":")
            имя = имя.strip().lower()
            значение = значение.replace("!important", "").strip()
            if имя in ("height", "max-height") and ВО_ВСЁ_ОКНО.match(значение):
                найдено.append("%s { %s: %s }" % (сел.strip(), имя, значение))
    return найдено


def сколько_правил_layout(css):
    return sum(1 for сел, _ in правила(css)
               if re.search(r"(^|[\s,>+~])\.layout(?![\w-])", сел))


class TestВысотаРабочейОбласти(unittest.TestCase):

    def setUp(self):
        self.css = io.open(СТИЛИ, encoding="utf-8").read()

    def test_разбор_вообще_видит_правила(self):
        """КОНТРОЛЬ НА ПУСТОТУ. Сломанный разбор дал бы ноль правил, и
        проверка ниже прошла бы, ничего не проверив."""
        сколько = сколько_правил_layout(self.css)
        self.assertGreaterEqual(сколько, 3,
                                "разбор нашёл всего %d правил .layout" % сколько)

    def test_высота_нигде_не_во_всё_окно(self):
        плохие = нарушения(self.css)
        self.assertEqual(плохие, [], "высота рабочей области задана во всё "
                                     "окно — шапка не вычтена: %s" % плохие)

    def test_базовое_правило_вычитает_шапку(self):
        """Мало запретить плохое — нужное должно быть на месте."""
        есть = [сел for сел, тело in правила(self.css)
                if ".layout" in сел and "--topbar-h" in тело
                and re.search(r"height\s*:", тело)]
        self.assertTrue(есть, "ни одно правило .layout не вычитает --topbar-h")

    def test_ловит_подсунутый_дефект(self):
        """ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: ровно то правило, что было сломано.

        Без него «нарушений нет» не значит ничего: пустой список возвращает и
        проверка, которая не умеет искать.
        """
        поддельный = """
        .layout { height: calc(100% - var(--topbar-h)); }
        @media (max-width: 900px) {
          .layout { height: 100%; max-height: 100%; overflow-y: auto; }
        }
        """
        плохие = нарушения(поддельный)
        self.assertEqual(len(плохие), 2, "не пойман явный дефект: %s" % плохие)

    def test_не_придирается_к_правильному(self):
        """ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: верный вариант не должен краснеть."""
        хороший = """
        .layout { height: calc(100% - var(--topbar-h)); }
        @media (max-width: 900px) {
          .layout { max-height: calc(100% - var(--topbar-h)); overflow-y: auto; }
        }
        .side__scroll { height: 100%; }
        """
        self.assertEqual(нарушения(хороший), [])


if __name__ == "__main__":
    unittest.main()
