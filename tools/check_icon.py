# -*- coding: utf-8 -*-
"""Проверяет собранный assets/MailFact.ico двумя независимыми способами.

1. ЕДИНЫЙ ИСТОЧНИК. Каждый кадр .ico сверяется с уменьшенным мастером.
   Сравнение идёт с НЕЗАВИСИМЫМ уменьшением (обычный LANCZOS в sRGB), а не с
   выходом нашего же конвейера: сравнивать конвейер сам с собой значит всегда
   получать ноль и ничего не проверять.

2. ЯРКОСТЬ. Средняя яркость кадра не должна уходить от мастера больше чем на
   5%. Эталон считается ПО МАСТЕРУ ПОПИКСЕЛЬНО, без всякого ресемплинга:
   первая версия такой проверки на соседнем проекте сравнивала с BOX-
   уменьшением, а оно само считает в sRGB — то есть эталон содержал ровно ту
   ошибку, которую проверка ищет, и был бесполезен.

У ОБОИХ ПОРОГОВ ЕСТЬ ОБРАТНЫЙ КОНТРОЛЬ. Без него порог мог бы быть настолько
широким, что пропускал бы что угодно:

  * в проверку единого источника подсовывается заведомо ЧУЖАЯ картинка —
    она обязана быть отвергнута;
  * в проверку яркости подсовывается наивное уменьшение в sRGB — то самое,
    ради поимки которого проверка и написана. Оно обязано провалиться.

    python tools/check_icon.py
"""
import os
import sys

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

import numpy as np
from PIL import Image

КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, КОРЕНЬ)

from tools.make_icon import (ИМЯ, РАЗМЕРЫ, _srgb_to_linear,  # noqa: E402
                             resize_linear)

ПОРОГ_ОТКЛОНЕНИЯ = 12.0      # уровней яркости 0..255
ПОРОГ_ЯРКОСТИ = 0.05         # 5%


def кадры_из_ico(путь):
    """Достаёт КАЖДЫЙ кадр .ico отдельно.

    `Image.open` отдаёт только один кадр; остальные достаются через .size,
    иначе проверялся бы один размер из десяти.
    """
    ico = Image.open(путь)
    из = {}
    for (w, h) in sorted(ico.info.get("sizes", [])):
        ico.size = (w, h)
        из[w] = ico.copy().convert("RGBA")
    return из


def отклонение(кадр, эталон):
    """Среднее отклонение по пикселям, видимым в ОБОИХ изображениях."""
    a = np.asarray(кадр.convert("RGBA"), dtype=np.float64)
    b = np.asarray(эталон.convert("RGBA"), dtype=np.float64)
    видно = (a[..., 3] > 32) & (b[..., 3] > 32)
    if видно.sum() == 0:
        return 255.0
    return float(np.abs(a[..., :3][видно] - b[..., :3][видно]).mean())


def яркость(img):
    """Средняя яркость в ЛИНЕЙНОМ свете, взвешенная на альфу.

    В линейном, потому что именно там яркость складывается физически: в sRGB
    просадку от уменьшения не увидеть, она спрятана в кривой гаммы. Взвешено
    на альфу, потому что прозрачные пиксели яркости не несут.
    """
    arr = np.asarray(img.convert("RGBA"), dtype=np.float64) / 255.0
    lin = _srgb_to_linear(arr[..., :3])
    lum = 0.2126 * lin[..., 0] + 0.7152 * lin[..., 1] + 0.0722 * lin[..., 2]
    w = arr[..., 3]
    if w.sum() < 1e-9:
        return 0.0
    return float((lum * w).sum() / w.sum())


def main():
    активы = os.path.join(КОРЕНЬ, "assets")
    путь_ico = os.path.join(активы, ИМЯ + ".ico")
    путь_png = os.path.join(активы, ИМЯ + ".png")
    for п in (путь_ico, путь_png):
        if not os.path.exists(п):
            print("нет файла:", п)
            return 1

    мастер = Image.open(путь_png).convert("RGBA")
    кадры = кадры_из_ico(путь_ico)
    плохо = 0

    print("размеров в .ico: %d" % len(кадры))
    if sorted(кадры) != sorted(РАЗМЕРЫ):
        print("НЕТ  состав размеров: %s, ждали %s" % (sorted(кадры),
                                                      sorted(РАЗМЕРЫ)))
        плохо += 1

    print()
    print("1. ЕДИНЫЙ ИСТОЧНИК (порог %.1f уровня)" % ПОРОГ_ОТКЛОНЕНИЯ)
    худшее = 0.0
    for size in sorted(кадры):
        эталон = мастер.resize((size, size), Image.LANCZOS)
        d = отклонение(кадры[size], эталон)
        худшее = max(худшее, d)
        ок = d <= ПОРОГ_ОТКЛОНЕНИЯ
        if not ок:
            плохо += 1
        print("  %s %3d px  отклонение %6.2f" % ("ok  " if ок else "НЕТ ",
                                                 size, d))
    print("  худшее отклонение: %.2f" % худшее)

    # Обратный контроль: заведомо чужая картинка. Не «похожая», а другая —
    # если проверка её пропустит, порог не проверяет ничего.
    чужая = Image.new("RGBA", (256, 256), (255, 0, 0, 255))
    d_чужой = отклонение(чужая, мастер.resize((256, 256), Image.LANCZOS))
    контроль_ок = d_чужой > ПОРОГ_ОТКЛОНЕНИЯ
    if not контроль_ок:
        плохо += 1
    print("  %s обратный контроль: чужая картинка даёт %.2f (порог %.1f)"
          % ("ok  " if контроль_ок else "НЕТ ", d_чужой, ПОРОГ_ОТКЛОНЕНИЯ))

    print()
    print("2. ЯРКОСТЬ (порог %.0f%%, эталон по мастеру попиксельно)"
          % (ПОРОГ_ЯРКОСТИ * 100))
    эталонная = яркость(мастер)
    print("  яркость мастера: %.6f" % эталонная)
    худшая = 0.0
    for size in sorted(кадры):
        я = яркость(кадры[size])
        доля = abs(я - эталонная) / эталонная if эталонная else 1.0
        худшая = max(худшая, доля)
        ок = доля <= ПОРОГ_ЯРКОСТИ
        if not ок:
            плохо += 1
        print("  %s %3d px  %.6f  отклонение %+6.2f%%"
              % ("ok  " if ок else "НЕТ ", size, я,
                 100.0 * (я - эталонная) / эталонная if эталонная else 0.0))
    print("  худшее отклонение яркости: %.2f%%" % (худшая * 100))

    # Обратный контроль яркости: наивное уменьшение в sRGB — тот самый дефект,
    # ради поимки которого проверка написана. Оно ОБЯЗАНО провалиться.
    наивно = мастер.resize((16, 16), Image.LANCZOS)
    я_наив = яркость(наивно)
    доля_наив = abs(я_наив - эталонная) / эталонная if эталонная else 0.0
    контроль2 = доля_наив > ПОРОГ_ЯРКОСТИ
    if not контроль2:
        плохо += 1
    print("  %s обратный контроль: наивный sRGB на 16 px даёт %+.2f%% "
          "(порог %.0f%%)" % ("ok  " if контроль2 else "НЕТ ",
                              100.0 * (я_наив - эталонная) / эталонная,
                              ПОРОГ_ЯРКОСТИ * 100))
    наш = яркость(resize_linear(мастер, 16))
    print("       для сравнения наш конвейер на 16 px: %+.2f%%"
          % (100.0 * (наш - эталонная) / эталонная))

    print()
    if плохо:
        print("ПРОВАЛОВ: %d" % плохо)
        return 1
    print("ICON_OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
