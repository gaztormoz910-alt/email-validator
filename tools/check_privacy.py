КОРЕНЬ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ИМЯ = "MailFact"

# Короче не бывает осмысленного маркера: имя компьютера «PC» нашлось бы в
# любом двоичном файле тысячу раз и утопило бы настоящие находки.
МИНИМУМ_ДЛИНЫ = 4

# Сколько символов с каждой стороны находки показывать. Хватает, чтобы понять,
# что это за строка, и не хватает, чтобы вывалить в журнал кусок двоичного мусора.
ОКРЕСТНОСТЬ = 40

# По сколько байт сжатого потока установщика подавать распаковщику. Весь
# поток — сотни мегабайт после распаковки, держать его в памяти целиком
# незачем. Константа, а не число в коде: тест уменьшает её до нескольких
# байт, чтобы маркер гарантированно лёг на стык порций.
ПОРЦИЯ = 8 << 20


# ─────────────────────────────── маркеры ────────────────────────────────

# Подпись маркеров, которые человек передал сам. Их значения никогда не
# печатаются: это может быть фамилия или домашний IP.
СВОЙ = "свой маркер"


def _формы_пути(путь):
    """Все написания одного пути, в которых он встречается внутри файлов.

    Один и тот же путь пишется по-разному в зависимости от того, кто его
    записал: Windows — через `\\`, Python и cmake — часто через `/`, JSON и
    исходники — с удвоенным `\\\\`, оболочка MSYS/Git Bash — как `/c/Users`.
    Ищем все, иначе пропустим ровно тот случай, который не пришёл в голову.
    """
    if not путь:
        return set()
    п = os.path.normpath(путь)
    формы = {п, п.replace("\\", "/"), п.replace("\\", "\\\\")}
    if len(п) > 2 and п[1] == ":":
        # C:\Users\x -> /c/Users/x
        формы.add("/" + п[0].lower() + п[2:].replace("\\", "/"))
    return {ф for ф in формы if len(ф) >= МИНИМУМ_ДЛИНЫ}


def _git(ключ):
    try:
        вывод = subprocess.run(["git", "config", "--get", ключ], cwd=КОРЕНЬ,
                               capture_output=True, text=True, timeout=10)
    except Exception:
        return ""
    return вывод.stdout.strip() if вывод.returncode == 0 else ""


def маркеры_машины(свои=()):
    """{подпись: множество строк} — что выдаёт машину, на которой идёт сборка."""
    м = {}

    def добавить(подпись, значения):
        годные = {з for з in значения if isinstance(з, str) and len(з.strip()) >= МИНИМУМ_ДЛИНЫ}
        if годные:
            м.setdefault(подпись, set()).update(з.strip() for з in годные)

    дом = os.path.expanduser("~")
    # НА СЕРВЕРЕ GITHUB ДОМАШНЯЯ ПАПКА — НЕ ЧЕЛОВЕК. Это общий аккаунт образа
    # (`C:\Users\runneradmin`, `/Users/runner`), один и тот же на всех машинах
    # GitHub. На нём же собраны тысячи чужих библиотек, и их пути в нашей
    # сборке есть всегда: замерено 25.09.2026 — 6998 вхождений
    # `runneradmin` в сторонних .pyd. Искать его значило бы ронять каждый
    # релиз на чужих путях и не узнать при этом ничего о себе. Путь проекта
    # и имя машины сервера остаются: они уникальны и ловят сам механизм утечки.
    if os.environ.get("GITHUB_ACTIONS") != "true":
        добавить("домашняя папка того, кто собирал", _формы_пути(дом))
        # Хвост «\Users\<имя>» без буквы диска: ловит и D:\Users\<имя>, и
        # сокращённые записи, где диск отрезан.
        имя_папки = os.path.basename(os.path.normpath(дом))
        родитель = os.path.basename(os.path.dirname(os.path.normpath(дом)))
        if имя_папки and родитель:
            хвост = os.sep + родитель + os.sep + имя_папки
            добавить("домашняя папка того, кто собирал", _формы_пути(хвост))

    добавить("папка проекта на машине сборки", _формы_пути(КОРЕНЬ))

    компьютер = {os.environ.get("COMPUTERNAME", ""), os.environ.get("HOSTNAME", "")}
    try:
        компьютер.add(socket.gethostname())
    except Exception:
        pass
    добавить("имя компьютера", компьютер)

    добавить("почта из git", {_git("user.email")})
    добавить("имя из git", {_git("user.name")})

    из_окружения = os.environ.get("MAILFACT_PRIVATE_MARKERS", "")
    добавить(СВОЙ, set(из_окружения.split(";")) | set(свои or ()))
    return м


def иглы(маркеры):
    """[(подпись, текст, байты)] — во всех кодировках, в которых ищем.

    Ищем в данных, приведённых к нижнему регистру по ASCII (`bytes.lower`).
    Кириллицу так не опустить, поэтому у не-ASCII маркера ищется ещё и его
    исходное написание — и в UTF-8, и в cp1251, в которой старые программы
    под русской Windows пишут пути.
    """
    out = []
    for подпись, значения in маркеры.items():
        for текст in sorted(значения):
            варианты = {текст.lower()}
            if not текст.isascii():
                варианты |= {текст, текст.upper(), текст.capitalize()}
            видели = set()
            for в in варианты:
                for кодировка in ("utf-8", "utf-16-le", "cp1251"):
                    try:
                        б = в.encode(кодировка)
                    except UnicodeEncodeError:
                        continue
                    if б not in видели:
                        видели.add(б)
                        out.append((подпись, текст, б))
    return out


