def проверить_архив_exe(exe, список_игл, отчёт, имя=None, счётчик="модулей PYZ"):
    """Записи архива PyInstaller внутри .exe, включая каждый модуль PYZ.

    Байткод в PYZ сжат zlib — поиск по сырому .exe его не видит вовсе. Именно
    туда попадают пути исходников (`co_filename`) и строки документации.
    """
    имя = имя or os.path.basename(exe)
    try:
        from PyInstaller.archive.readers import CArchiveReader
    except Exception as e:
        отчёт.не_разобрано.append((имя, "нет читателя архивов PyInstaller: %s" % e))
        return
    try:
        архив = CArchiveReader(exe)
    except Exception as e:
        отчёт.не_разобрано.append((имя, "архив PyInstaller не открылся: %s" % e))
        return
    отчёт.счётчики.setdefault(счётчик, 0)
    for запись in list(архив.toc):
        где = "%s#%s" % (имя, запись)
        if isinstance(запись, str) and запись.upper().endswith(".PYZ"):
            try:
                pyz = архив.open_embedded_archive(запись)
            except Exception as e:
                отчёт.не_разобрано.append((где, "PYZ не открылся: %s" % e))
                continue
            for модуль in list(pyz.toc):
                try:
                    данные = pyz.extract(модуль, raw=True)
                except Exception as e:
                    отчёт.не_разобрано.append(("%s/%s" % (где, модуль), str(e)))
                    continue
                if данные is None:      # пакет-пространство имён: данных нет
                    continue
                отчёт.счётчики[счётчик] += 1
                искать(данные, "%s/%s" % (где, модуль), список_игл, отчёт)
            continue
        try:
            данные = архив.extract(запись)
        except Exception as e:
            отчёт.не_разобрано.append((где, str(e)))
            continue
        отчёт.счётчики["записей архива .exe"] += 1
        искать(данные, где, список_игл, отчёт)


# ───────────────────────────── установщик ───────────────────────────────

_ПОДПИСЬ_INNO = b"Inno Setup Setup Data ("


def _lzma1(сырое):
    """LZMA1 так, как его пишет Inno: 5 байт свойств, затем поток без длины."""
    if len(сырое) < 5:
        raise ValueError("блок короче заголовка LZMA")
    d = сырое[0]
    lc, d = d % 9, d // 9
    lp, pb = d % 5, d // 5
    словарь = struct.unpack_from("<I", сырое, 1)[0]
    распаковщик = lzma.LZMADecompressor(lzma.FORMAT_RAW, filters=[{
        "id": lzma.FILTER_LZMA1, "lc": lc, "lp": lp, "pb": pb,
        "dict_size": словарь}])
    return распаковщик.decompress(bytes(сырое[5:]))


def _блок_inno(данные, pos):
    """Один сжатый блок setup-0. Возвращает (распакованное, конец) либо None.

    Устройство: CRC32 заголовка, размер, флаг сжатия; дальше данные кусками
    по 4096 байт, перед каждым свой CRC32. Ширина поля размера у версий Inno
    разная (4 или 8 байт), поэтому пробуем обе и верим только той, у которой
    сошлась контрольная сумма: угаданная раскладка без проверки CRC
    «разобрала» бы мусор и объявила его чистым.
    """
    for формат in ("<IB", "<QB"):
        ширина = struct.calcsize(формат)
        if pos + 4 + ширина > len(данные):
            continue
        crc = struct.unpack_from("<I", данные, pos)[0]
        if zlib.crc32(данные[pos + 4: pos + 4 + ширина]) & 0xFFFFFFFF != crc:
            continue
        размер, сжат = struct.unpack_from(формат, данные, pos + 4)
        p = pos + 4 + ширина
        конец_блока = p + размер
        if конец_блока > len(данные):
            continue
        сырое = bytearray()
        целый = True
        while p < конец_блока:
            crc_куска = struct.unpack_from("<I", данные, p)[0]
            p += 4
            n = min(4096, конец_блока - p)
            кусок = данные[p: p + n]
            if zlib.crc32(кусок) & 0xFFFFFFFF != crc_куска:
                целый = False
                break
            сырое += кусок
            p += n
        if not целый:
            continue
        return (_lzma1(сырое) if сжат else bytes(сырое)), конец_блока
    return None


def _запись_с_crc(данные, pos, до=256):
    """Длина записи «CRC32 + тело», начинающейся в pos, либо None.

    Inno Setup 6.5+ кладёт между подписью и первым блоком запись о шифровании
    (есть ли пароль, соль, число итераций) со своей контрольной суммой. Длину
    её не угадываем по номеру версии, а находим по сошедшейся CRC.
    """
    if pos + 4 > len(данные):
        return None
    crc = struct.unpack_from("<I", данные, pos)[0]
    for длина in range(1, до + 1):
        if zlib.crc32(данные[pos + 4: pos + 4 + длина]) & 0xFFFFFFFF == crc:
            return длина
    return None


def _блоки_после(данные, pos):
    """Все сжатые блоки setup-0 подряд, начиная с pos. ([блоки], конец)."""
    блоки = []
    блок = _блок_inno(данные, pos)
    if блок is None:
        длина = _запись_с_crc(данные, pos)
        if длина is None:
            return [], pos
        # Первый байт записи — используется ли шифрование. Зашифрованный
        # заголовок без пароля не прочитать, и притворяться, что прочитали,
        # нельзя: тогда блоки просто не сойдутся и часть уйдёт в «не разобрано».
        pos += 4 + длина
        блок = _блок_inno(данные, pos)
    while блок is not None:
        распаковано, pos = блок
        блоки.append(распаковано)
        блок = _блок_inno(данные, pos)
    return блоки, pos


def _размер_словаря_lzma2(p):
    if p > 40:
        raise ValueError("неверное свойство LZMA2: %d" % p)
    if p == 40:
        return 0xFFFFFFFF
    return (2 | (p & 1)) << (p // 2 + 11)


def _начало_потока(данные):
    """Где начинается сжатый поток с файлами (setup-1): кусок «zlb\\x1a» + LZMA2.

    Стоит он у разных версий Inno по-разному — у 6.7 сразу за загрузчиком, ДО
    заголовка, у старых после. Поэтому ищем по всему файлу и берём первое
    вхождение, с которого LZMA2 действительно распаковывается: те же четыре
    байта могут случайно попасться в коде загрузчика.
    """
    i = данные.find(b"zlb\x1a")
    while i >= 0:
        try:
            пробный = lzma.LZMADecompressor(lzma.FORMAT_RAW, filters=[{
                "id": lzma.FILTER_LZMA2, "dict_size": _размер_словаря_lzma2(данные[i + 4])}])
            пробный.decompress(данные[i + 5: i + 5 + 65536], max_length=4096)
            return i
        except (lzma.LZMAError, ValueError, IndexError):
            i = данные.find(b"zlb\x1a", i + 1)
    return None


def _поток_файлов(данные, где, список_игл, отчёт):
    """Распаковывает поток с файлами и ищет в нём.

    Распаковываем порциями и ищем в каждой с перекрытием: иначе маркер,
    разрезанный границей порции, прошёл бы незамеченным.
    """
    i = _начало_потока(данные)
    if i is None:
        отчёт.не_разобрано.append((где, "не найден сжатый поток с файлами"))
        return 0
    p = i + 4
    распаковщик = lzma.LZMADecompressor(lzma.FORMAT_RAW, filters=[{
        "id": lzma.FILTER_LZMA2, "dict_size": _размер_словаря_lzma2(данные[p])}])
    p += 1
    хвост = b""
    перекрытие = max((len(б) for _, _, б in список_игл), default=0)
    всего = 0
    начало = bytearray()
    try:
        while p < len(данные) and not распаковщик.eof:
            порция = распаковщик.decompress(данные[p: p + ПОРЦИЯ])
            p += ПОРЦИЯ
            всего += len(порция)
            if len(начало) < НАЧАЛО_ПОТОКА:
                начало += порция[:НАЧАЛО_ПОТОКА - len(начало)]
            окно = хвост + порция
            искать(окно, где + " (сжатые файлы)", список_игл, отчёт)
            хвост = окно[-перекрытие:] if перекрытие else b""
    except lzma.LZMAError as e:
        отчёт.не_разобрано.append((где, "поток с файлами оборвался: %s" % e))
        return всего, bytes(начало)
    if not распаковщик.eof:
        отчёт.не_разобрано.append((где, "поток с файлами не дочитан до конца"))
    return всего, bytes(начало)


# Сколько начала распакованного потока держать в памяти, чтобы достать из него
# саму программу. Она идёт в потоке первой (корень сборки раньше _internal), и
# весит два десятка мегабайт; запас — на рост.
НАЧАЛО_ПОТОКА = 96 << 20

# Хвост архива PyInstaller: подпись и длина архива. Формат '!8sIIii64s'.
_ПЕЧЕНЬЕ_PYI = b"MEI\x0c\x0b\x0a\x0b\x0e"
_ДЛИНА_ПЕЧЕНЬЯ = 88

# Фильтр работает кусками по 64 КиБ от начала файла.
_КУСОК_ФИЛЬТРА = 0x10000


def снять_фильтр_вызовов(данные):
    """Обратный ход фильтра, которым Inno Setup обрабатывает .exe и .dll перед сжатием.

    ЗАЧЕМ. Ради лучшего сжатия Inno переписывает в исполняемых файлах адреса
    после команд CALL и JMP (байты E8 и E9): относительный адрес становится
    абсолютным. Для машинного кода это безвредно, а вот архив PyInstaller
    внутри .exe — сжатые zlib данные, и в них такие байты попадаются
    случайно. Без обратного хода байткод программы из установщика не
    распаковывается, и опубликованный файл до строк документации не проверить.

    КАК ВЫВЕДЕНО. Не по памяти и не по чужому описанию, а по оракулу: .exe из
    потока установщика, собранного Inno 6.7.3, сверен с исходным .exe из
    папки сборки. Совпадение байт в байт — 22 415 130 из 22 415 130 — дал
    ровно один из шести перебранных вариантов: этот. Любой другой оставлял
    от 226 до 2438 расхождений.

    ЧЕГО ОРАКУЛ НЕ ПРОВЕРИЛ. Правило границы куска (команда в последних
    четырёх байтах 64 КиБ не трогается) в том файле ни разу не сработало —
    таких мест в нём не нашлось. Если оно неверно, испорченным окажется
    модуль, который не распакуется, и он уйдёт в «не разобрано», а не в
    «чисто»: ложной чистоты эта ошибка дать не может.
    """
    b = bytearray(данные)
    n = len(b)
    for c in range(0, n, _КУСОК_ФИЛЬТРА):
        предел = c + min(_КУСОК_ФИЛЬТРА, n - c) - 4
        i = c
        while i < предел:
            e8 = b.find(b"\xe8", i, предел)
            e9 = b.find(b"\xe9", i, предел)
            кандидаты = [x for x in (e8, e9) if x >= 0]
            if not кандидаты:
                break
            i = min(кандидаты) + 1              # первый байт адреса
            if b[i + 3] in (0x00, 0xFF):
                адрес = (i + 4) & 0xFFFFFF      # от начала файла, за адресом
                закодированный = b[i] | b[i + 1] << 8 | b[i + 2] << 16
                отн = (закодированный - адрес) & 0xFFFFFF
                b[i] = отн & 0xFF
                b[i + 1] = (отн >> 8) & 0xFF
                b[i + 2] = отн >> 16
                if отн & 0x800000:
                    b[i + 3] ^= 0xFF
            i += 4
    return bytes(b)


def программа_из_потока(начало, где, список_игл, отчёт):
    """Достаёт собранную программу из потока установщика и смотрит её архив.

    Где в потоке кончается .exe, говорит хвост архива PyInstaller; где он
    начинается — нет. Поэтому идём назад по заголовкам «MZ» и берём первый,
    с которого после снятия фильтра архив открывается и модули распаковываются:
    неверное начало сдвигает адреса, и zlib это увидит сразу.
    """
    import tempfile
    k = начало.find(_ПЕЧЕНЬЕ_PYI)
    if k < 0:
        отчёт.не_разобрано.append((где, "в потоке нет архива PyInstaller — программа не просмотрена"))
        return False
    конец = k + _ДЛИНА_ПЕЧЕНЬЯ
    длина_архива = struct.unpack_from("!I", начало, k + 8)[0]
    начало_архива = конец - длина_архива
    j = начало.rfind(b"MZ", 0, max(0, начало_архива) + 1)
    while j >= 0 and начало_архива - j <= 32 << 20:
        exe = снять_фильтр_вызовов(начало[j:конец])
        fd, путь = tempfile.mkstemp(suffix=".exe")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(exe)
            if _архив_цел(путь):
                проверить_архив_exe(путь, список_игл, отчёт, имя=где + " → " + ИМЯ + ".exe",
                                    счётчик="модулей PYZ (из установщика)")
                return True
        finally:
            try:
                os.remove(путь)
            except OSError:
                pass
        j = начало.rfind(b"MZ", 0, j)
    отчёт.не_разобрано.append((где, "архив PyInstaller в потоке не восстановился"))
    return False


def _архив_цел(путь):
    """Открывается ли архив и распаковываются ли первые модули PYZ."""
    try:
        from PyInstaller.archive.readers import CArchiveReader
        архив = CArchiveReader(путь)
        имена = [k for k in архив.toc if isinstance(k, str) and k.upper().endswith(".PYZ")]
        if not имена:
            return False
        pyz = архив.open_embedded_archive(имена[0])
        for модуль in list(pyz.toc)[:20]:
            pyz.extract(модуль, raw=True)
        return True
    except Exception:
        return False


# Секунд между 1601-01-01 (начало отсчёта FILETIME в Windows) и 1970-01-01.
_ЭПОХА_FILETIME = 11644473600

# Сколько файлов сборки сверять по времени. Сдвиг пояса, если он есть,
# одинаков у всех файлов, поэтому сотни хватает с запасом, а полный перебор
# тысяч файлов по мегабайтам заголовка стоил бы лишних секунд на каждой сборке.
ФАЙЛОВ_ДЛЯ_ВРЕМЕНИ = 300


def _filetime(unix):
    # Inno по умолчанию округляет время вниз до двух секунд (TimeStampRounding=2).
    с = int(unix) - int(unix) % 2
    return struct.pack("<Q", (с + _ЭПОХА_FILETIME) * 10 ** 7)


def пояс_в_заголовке(заголовок, папка, смещение):
    """(по UTC, по местному времени, сверено файлов) для времени файлов в установщике.

    Inno Setup по умолчанию хранит время файлов в МЕСТНОМ времени машины
    сборки. Тогда у получателя время файлов расходится со временем публикации
    ровно на часовой пояс того, кто собирал. Ищем в заголовке время каждого
    файла дважды: как есть (UTC) и со сдвигом на пояс этой машины.
    """
    по_utc = по_местному = сверено = 0
    for корень, _папки, файлы in os.walk(папка):
        for имя in sorted(файлы):
            if сверено >= ФАЙЛОВ_ДЛЯ_ВРЕМЕНИ:
                return по_utc, по_местному, сверено
            try:
                м = os.path.getmtime(os.path.join(корень, имя))
            except OSError:
                continue
            сверено += 1
            if _filetime(м) in заголовок:
                по_utc += 1
            elif смещение and _filetime(м + смещение) in заголовок:
                по_местному += 1
    return по_utc, по_местному, сверено


def проверить_установщик(путь, список_игл, отчёт, папка=None, смещение=None, программа=True):
    """Установщик целиком. `программа=False` — только для синтетических
    установщиков в тестах, где собранной программы внутри нет."""
    где = os.path.basename(путь)
    try:
        with open(путь, "rb") as f:
            данные = f.read()
    except OSError as e:
        отчёт.не_разобрано.append((где, str(e)))
        return {}
    # Несжатые части: загрузчик, ресурсы, «Свойства → Подробно».
    искать(данные, где, список_игл, отчёт)
    чужие_пути(данные, где, отчёт)

    итог = {"байт установщика": len(данные)}
    # Подпись может встречаться и внутри кода загрузчика как константа, поэтому
    # перебираем все вхождения и берём то, за которым блок сходится по CRC.
    i = данные.find(_ПОДПИСЬ_INNO)
    while i >= 0:
        блоки, _конец = _блоки_после(данные, i + 64)
        if блоки:
            for n, б in enumerate(блоки):
                искать(б, "%s (заголовок Inno, блок %d)" % (где, n), список_игл, отчёт)
            итог["заголовок Inno, блоков"] = len(блоки)
            итог["заголовок Inno, байт"] = sum(len(б) for б in блоки)
            итог["сжатые файлы, байт"], начало = _поток_файлов(данные, где, список_игл, отчёт)
            if программа:
                программа_из_потока(начало, где, список_игл, отчёт)
            if папка:
                if смещение is None:
                    смещение = time.localtime().tm_gmtoff or 0
                utc, местн, всего = пояс_в_заголовке(b"".join(блоки), папка, смещение)
                итог["время файлов: по UTC"] = "%d из %d" % (utc, всего)
                итог["время файлов: местное"] = "%d из %d" % (местн, всего)
                if местн:
                    отчёт.находка(
                        "часовой пояс машины сборки", "UTC%+g" % (смещение / 3600.0),
                        где + " (время файлов в заголовке Inno)",
                        "%d из %d файлов записаны в местном времени; нужен "
                        "TimeStampsInUTC=yes в MailFact.iss" % (местн, всего))
            return итог
        i = данные.find(_ПОДПИСЬ_INNO, i + 1)
    отчёт.не_разобрано.append((где, "заголовок Inno Setup не найден или не сошёлся по CRC"))
    return итог


