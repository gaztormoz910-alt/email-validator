"""Нет ли в собранной программе и в установщике следов машины, где их собрали.

ЗАЧЕМ. Файл сам по себе IP-адреса не знает: адрес попадает в файл только если
его туда кто-то записал. Зато в сборку легко утекает другое — путь вида
`C:\\Users\\<имя>\\...`, имя компьютера, имя и почта из git. Утекают они
незаметно: через пути в байткоде, через метаданные пакетов, через отладочные
пути внутри .dll. Глазами этого не увидеть, потому что почти всё содержимое
сжато — байткод в архиве PYZ, файлы установщика в потоке LZMA2.

Поэтому проверка разворачивает всё, что сжато, и ищет уже в развёрнутом:

  1. каждый файл папки сборки — как есть;
  2. каждый член zip-архивов внутри неё (base_library.zip и прочие);
  3. каждую запись архива PyInstaller внутри .exe, включая модули PYZ;
  4. установщик: его несжатые части, заголовок Inno Setup (LZMA1) и сжатый
     поток с файлами (LZMA2).

ЧТО ИЩЕТСЯ. Маркеры ВЫЧИСЛЯЮТСЯ на машине, где идёт проверка, а не зашиты в
этот файл: зашить сюда своё имя значило бы опубликовать его в открытом
репозитории — ровно то, от чего проверка защищает. На машине владельца это
его домашняя папка, путь проекта, имя компьютера и данные git. На сервере
GitHub — такие же данные сервера сборки.

Свои дополнительные маркеры (фамилия, внешний IP) можно передать через
`--marker` или переменную окружения MAILFACT_PRIVATE_MARKERS (через `;`) —
и тогда они тоже никуда не записываются.

ЧЕГО ПРОВЕРКА НЕ УТВЕРЖДАЕТ. Если какую-то часть не удалось развернуть,
ответ — «не проверено» (код 2), а не «чисто»: чистота непросмотренного
неизвестна.

    python tools/check_privacy.py --dist dist/MailFact --installer installer/MailFact-setup.exe
"""
