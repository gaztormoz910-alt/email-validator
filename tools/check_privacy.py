def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--dist", help="папка сборки PyInstaller (dist/MailFact или .app)")
    p.add_argument("--installer", help="готовый установщик Inno Setup")
    p.add_argument("--marker", action="append", default=[],
                   help="дополнительная строка, которой не должно быть в сборке")
    a = p.parse_args(argv)
    if not a.dist and not a.installer:
        p.error("нужен --dist, --installer или оба")

    маркеры = маркеры_машины(a.marker)
    список = иглы(маркеры)
    # Свои маркеры на сервере GitHub приходят из секрета — и журнал сборки не
    # должен их показать ни при каком исходе. GitHub прячет в журнале только
    # секрет целиком, а маркеры в нём через `;`, поэтому каждый объявляется
    # скрываемым отдельно, до любого вывода.
    if os.environ.get("GITHUB_ACTIONS") == "true":
        for значение in sorted(маркеры.get(СВОЙ, ())):
            print("::add-mask::" + значение)
    print("ищем следы машины сборки:")
    for подпись in sorted(маркеры):
        print("  %-34s %d написаний" % (подпись, len(маркеры[подпись])))
    if not список:
        print("ПРОВАЛ: не удалось вычислить ни одного маркера — искать нечего")
        return 2

    отчёт = Отчёт()
    if a.dist:
        if not os.path.isdir(a.dist):
            print("ПРОВАЛ: нет папки сборки:", a.dist)
            return 2
        проверить_папку(a.dist, список, отчёт)
        exe = найти_исполняемый(a.dist)
        if exe is None:
            отчёт.не_разобрано.append((a.dist, "не найден исполняемый файл %s" % ИМЯ))
        else:
            проверить_архив_exe(exe, список, отчёт)
    итог_установщика = {}
    if a.installer:
        # Папка сборки нужна и здесь: по времени её файлов видно, в каком
        # поясе записаны отметки внутри установщика.
        итог_установщика = проверить_установщик(
            a.installer, список, отчёт,
            папка=a.dist if a.dist and os.path.isdir(a.dist) else None)

    print()
    for ключ, значение in отчёт.счётчики.items():
        print("  просмотрено %-22s %s" % (ключ, значение))
    for ключ, значение in итог_установщика.items():
        print("  установщик: %-22s %s" % (ключ, значение))

    # Своя домашняя папка в этот список не попадает: если она нашлась, это не
    # «чужой путь», а находка, и она уже стоит в разделе ниже.
    свой = os.path.basename(os.path.normpath(os.path.expanduser("~"))).lower()
    чужие = {к: з for к, з in отчёт.чужие_пути.items() if к.lower() != свой}
    if чужие:
        print()
        print("пути ЧУЖИХ машин (авторы библиотек собирали их у себя; к нам не относятся):")
        for имя, (сколько, первый) in sorted(чужие.items(), key=lambda x: -x[1][0])[:15]:
            print("  %-24s %5d раз, например в %s" % (имя, сколько, первый))

    print()
    if отчёт.находки:
        print("НАЙДЕНЫ СЛЕДЫ МАШИНЫ СБОРКИ (%d):" % len(отчёт.находки))
        свои = sorted(маркеры.get(СВОЙ, ()))
        for подпись, текст, где, окрестность in отчёт.находки:
            if подпись == СВОЙ:
                # Ни значения, ни окрестности: окрестность содержит его же.
                # Номер — чтобы владелец понял, какой из его маркеров нашёлся.
                номер = свои.index(текст) + 1 if текст in свои else 0
                print("  [%s №%d] значение скрыто" % (подпись, номер))
                print("      где: %s" % где)
                continue
            print("  [%s] %r" % (подпись, текст))
            print("      где: %s" % где)
            print("      вокруг: %s" % окрестность)
    if отчёт.не_разобрано:
        print("НЕ РАЗОБРАНО (%d) — про эти части ничего утверждать нельзя:" % len(отчёт.не_разобрано))
        for где, почему in отчёт.не_разобрано[:30]:
            print("  %s: %s" % (где, почему))
    if отчёт.находки:
        return 1
    if отчёт.не_разобрано:
        return 2
    print("ЧИСТО: следов машины сборки не найдено — PRIVACY-CLEAN")
    return 0


if __name__ == "__main__":
    sys.exit(main())
