class Отчёт:
    def __init__(self):
        self.находки = []          # (подпись, текст, где, окрестность)
        self.не_разобрано = []     # (где, почему)
        self.счётчики = {"файлов": 0, "байт": 0, "членов zip": 0,
                         "модулей PYZ": 0, "записей архива .exe": 0}
        self.чужие_пути = {}       # имя -> (сколько, первый файл)

    def находка(self, подпись, текст, где, окрестность):
        # Одну и ту же строку в одном месте считаем один раз: кодировок
        # несколько, а утечка одна.
        ключ = (подпись, текст, где)
        if any((н[0], н[1], н[2]) == ключ for н in self.находки):
            return
        self.находки.append((подпись, текст, где, окрестность))


def _окрестность(данные, i, длина):
    кусок = данные[max(0, i - ОКРЕСТНОСТЬ): i + длина + ОКРЕСТНОСТЬ]
    текст = кусок.replace(b"\x00", b"").decode("utf-8", "replace")
    return "".join(с if с.isprintable() else "·" for с in текст)


def искать(данные, где, список_игл, отчёт):
    """Ищет все иглы в одном куске данных."""
    if not данные:
        return
    низ = данные.lower()
    for подпись, текст, б in список_игл:
        i = низ.find(б)
        if i < 0 and not текст.isascii():
            i = данные.find(б)
        if i >= 0:
            отчёт.находка(подпись, текст, где, _окрестность(данные, i, len(б)))


# Пути ЧУЖИХ машин: библиотеки, собранные их авторами, несут в .dll и .pyd
# отладочные пути вида C:\Users\<сборщик>\... Это не утечка владельца, но
# показать их надо — «кристально чисто» без этой оговорки было бы неправдой.
_ЧУЖОЙ_ПУТЬ = re.compile(rb"[A-Za-z]:[\\/]{1,2}Users[\\/]{1,2}([A-Za-z0-9_.\- ]{1,40})[\\/]")


def чужие_пути(данные, где, отчёт):
    for m in _ЧУЖОЙ_ПУТЬ.finditer(данные):
        имя = m.group(1).decode("ascii", "replace")
        сколько, первый = отчёт.чужие_пути.get(имя, (0, где))
        отчёт.чужие_пути[имя] = (сколько + 1, первый)


# ─────────────────────────── папка сборки ───────────────────────────────

def проверить_zip(путь, где, список_игл, отчёт):
    try:
        with zipfile.ZipFile(путь) as z:
            for член in z.infolist():
                if член.is_dir():
                    continue
                try:
                    данные = z.read(член)
                except Exception as e:
                    отчёт.не_разобрано.append(("%s!%s" % (где, член.filename), str(e)))
                    continue
                отчёт.счётчики["членов zip"] += 1
                искать(данные, "%s!%s" % (где, член.filename), список_игл, отчёт)
    except (zipfile.BadZipFile, OSError) as e:
        отчёт.не_разобрано.append((где, "zip не открылся: %s" % e))


def проверить_папку(папка, список_игл, отчёт):
    for корень, _папки, файлы in os.walk(папка):
        for имя in файлы:
            путь = os.path.join(корень, имя)
            где = os.path.relpath(путь, папка).replace("\\", "/")
            try:
                with open(путь, "rb") as f:
                    данные = f.read()
            except OSError as e:
                отчёт.не_разобрано.append((где, str(e)))
                continue
            отчёт.счётчики["файлов"] += 1
            отчёт.счётчики["байт"] += len(данные)
            искать(данные, где, список_игл, отчёт)
            чужие_пути(данные, где, отчёт)
            # Сигнатура zip в начале — не расширение: .whl, .egg, .zip и
            # файлы данных без расширения устроены одинаково.
            if данные[:4] == b"PK\x03\x04":
                проверить_zip(путь, где, список_игл, отчёт)


